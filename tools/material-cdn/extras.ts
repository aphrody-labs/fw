#!/usr/bin/env bun
// material-cdn step 2b: the parts of the /v1 tree that do not come from Google: M3 design tokens and the Aphrody icon set.
//   bun tools/material-cdn/extras.ts [--out DIR] [--tokens FILE] [--aphrody DIR]
// Adds to out/v1 (existing files are kept, so run it after build.ts):
//   tokens/m3.css         custom properties --md-<path>: colour roles per scheme (light, dark, ...) under [data-scheme], everything else under :root
//   tokens/m3.json        the TOML tree as JSON
//   tokens/m3.dtcg.json   the same tokens in the W3C Design Tokens Community Group format ($type, $value)
//   aphrody/icons/<name>.svg, aphrody/index.json   the SVGs of aphrody/assets/icons verbatim, with viewBox, bytes and sha256 (skipped when the directory is absent)
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

const args = process.argv.slice(2);
const opt = (name: string, fallback: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? args[i + 1]! : fallback;
};
const root = resolve(import.meta.dir, "..", "..");
const out = resolve(opt("out", ".cache/material-cdn-out"));
const tokensPath = resolve(opt("tokens", join(root, "crates", "fw-m3", "tokens", "google_design_tokens.toml")));
const aphrodyDir = resolve(opt("aphrody", join(root, "..", "aphrody", "assets", "icons")));
const v1 = join(out, "v1");
const sha256 = (data: string | Uint8Array) => new Bun.CryptoHasher("sha256").update(data).digest("hex");

// ---------------------------------------------------------------- tokens
type Tree = { [key: string]: Scalar | Scalar[] | Tree };
type Scalar = string | number | boolean;
const tokensToml = await readFile(tokensPath, "utf8");
const tree = Bun.TOML.parse(tokensToml) as Tree;
const isTree = (v: unknown): v is Tree => typeof v === "object" && v !== null && !Array.isArray(v);

const UNIT: Record<string, string> = { px: "px", dp: "px", sp: "px", deg: "deg", ms: "ms" };
const unitOf = (key: string) => UNIT[key.slice(key.lastIndexOf("_") + 1)];
const dash = (path: string[]) => path.join("-").replaceAll("_", "-");

const SCHEMES = "sys.color.";
const schemeSelector = (name: string) => (name === "light" ? `:root,[data-scheme="light"]` : `[data-scheme="${name.replaceAll("_", "-")}"]`);
const rootVars: string[] = [];
const schemes = new Map<string, string[]>();
function cssValue(path: string[], value: Scalar): string {
  const key = path[path.length - 1]!;
  if (typeof value === "number") return unitOf(key) ? `${value}${unitOf(key)}` : String(value);
  if (typeof value === "boolean") return value ? "1" : "0";
  if (path.includes("typeface") || /^#[0-9a-fA-F]{3,8}$/.test(value)) return value;
  return JSON.stringify(value);
}
(function walkCss(node: Tree, path: string[]) {
  for (const [key, value] of Object.entries(node)) {
    const next = [...path, key];
    if (isTree(value)) walkCss(value, next);
    else if (!Array.isArray(value) && path.length > 0) {
      const dotted = next.join(".");
      if (dotted.startsWith(SCHEMES) && next.length === 4) {
        const scheme = next[2]!;
        if (!schemes.has(scheme)) schemes.set(scheme, []);
        schemes.get(scheme)!.push(`--md-sys-color-${key.replaceAll("_", "-")}:${cssValue(next, value)}`);
      } else rootVars.push(`--md-${dash(next)}:${cssValue(next, value)}`);
    }
  }
})(tree, []);
let css = `/* Material 3 design tokens of fw-m3 (crates/fw-m3/tokens/google_design_tokens.toml, sha256 ${sha256(tokensToml).slice(0, 12)}). Generated by tools/material-cdn/extras.ts. */\n`;
css += `:root{\n${rootVars.map((v) => `  ${v};`).join("\n")}\n}\n`;
for (const [scheme, vars] of schemes) css += `${schemeSelector(scheme)}{color-scheme:${scheme === "light" ? "light" : "dark"};\n${vars.map((v) => `  ${v};`).join("\n")}\n}\n`;
const dark = schemes.get("dark");
if (dark) css += `@media (prefers-color-scheme:dark){:root:not([data-scheme]){color-scheme:dark;\n${dark.map((v) => `  ${v};`).join("\n")}\n}}\n`;

// DTCG (2025.10): colour objects, dimension objects, fontFamily arrays; plain numbers elsewhere, the unit kept in an extension.
function hexColor(hex: string) {
  const h = hex.slice(1);
  const full = h.length <= 4 ? [...h].map((c) => c + c).join("") : h;
  const channel = (i: number) => Math.round((parseInt(full.slice(i * 2, i * 2 + 2), 16) / 255) * 1e4) / 1e4;
  const color: { colorSpace: string; components: number[]; alpha?: number; hex: string } = { colorSpace: "srgb", components: [channel(0), channel(1), channel(2)], hex: `#${full.slice(0, 6).toUpperCase()}` };
  if (full.length === 8) color.alpha = channel(3);
  return color;
}
function dtcgToken(path: string[], value: Scalar): Record<string, unknown> {
  const key = path[path.length - 1]!;
  if (typeof value === "string" && /^#[0-9a-fA-F]{3,8}$/.test(value)) return { $type: "color", $value: hexColor(value) };
  if (typeof value === "string" && path.includes("typeface")) return { $type: "fontFamily", $value: value.split(",").map((f) => f.trim()) };
  if (typeof value === "number") {
    const unit = unitOf(key);
    if (unit === "px" && key.endsWith("_px")) return { $type: "dimension", $value: { value, unit: "px" } };
    if (key === "weight" || key.endsWith("_weight")) return { $type: "fontWeight", $value: value };
    return unit ? { $type: "number", $value: value, $extensions: { "com.aphrody.unit": key.slice(key.lastIndexOf("_") + 1) } } : { $type: "number", $value: value };
  }
  return { $type: typeof value === "boolean" ? "boolean" : "string", $value: value };
}
const meta: Record<string, unknown> = {};
const dtcg = (function walk(node: Tree, path: string[]): Record<string, unknown> {
  const group: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) {
    if (isTree(value)) group[key] = walk(value, [...path, key]);
    else if (Array.isArray(value) || path.length === 0) meta[key] = value;
    else group[key] = dtcgToken([...path, key], value);
  }
  return group;
})(tree, []);
dtcg.$extensions = { "com.aphrody": { source: "crates/fw-m3/tokens/google_design_tokens.toml", sha256: sha256(tokensToml), ...meta } };

await mkdir(join(v1, "tokens"), { recursive: true });
await writeFile(join(v1, "tokens", "m3.css"), css);
await writeFile(join(v1, "tokens", "m3.json"), JSON.stringify(tree));
await writeFile(join(v1, "tokens", "m3.dtcg.json"), JSON.stringify(dtcg));
const countTokens = (g: Record<string, unknown>): number => Object.entries(g).reduce((n, [k, v]) => (k.startsWith("$") ? n : n + ("$value" in (v as object) ? 1 : countTokens(v as Record<string, unknown>))), 0);
console.log(`tokens: ${rootVars.length + [...schemes.values()].reduce((n, v) => n + v.length, 0)} css variables in ${schemes.size} schemes, ${countTokens(dtcg)} dtcg tokens`);

// ---------------------------------------------------------------- aphrody icons
if (existsSync(aphrodyDir)) {
  const files: string[] = [];
  const walk = async (dir: string) => {
    for (const e of await readdir(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) await walk(p);
      else if (e.name.endsWith(".svg")) files.push(p);
    }
  };
  await walk(aphrodyDir);
  files.sort();
  const rows: { name: string; viewBox: string | null; bytes: number; sha256: string }[] = [];
  for (const file of files) {
    const name = relative(aphrodyDir, file).split(sep).join("/").slice(0, -4);
    const body = new Uint8Array(await Bun.file(file).arrayBuffer());
    const text = new TextDecoder().decode(body);
    const dest = join(v1, "aphrody", "icons", `${name}.svg`);
    await mkdir(join(dest, ".."), { recursive: true });
    await Bun.write(dest, body);
    rows.push({ name, viewBox: /viewBox="([^"]+)"/.exec(text)?.[1] ?? null, bytes: body.length, sha256: sha256(body) });
  }
  await writeFile(join(v1, "aphrody", "index.json"), JSON.stringify({ set: "aphrody", path: "aphrody/icons/<name>.svg", count: rows.length, icons: rows }));
  console.log(`aphrody: ${rows.length} icons from ${aphrodyDir}`);
} else console.log(`aphrody: ${aphrodyDir} not found, skipped`);
