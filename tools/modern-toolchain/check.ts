#!/usr/bin/env bun
// Gates of the modern-toolchain lot, driven by tools/modern-toolchain/steps.toml.
//   bun tools/modern-toolchain/check.ts ignore    tracked files must not match an ignore rule or be build output;
//                                                 .dockerignore must equal the set generated from steps.toml and .gitignore (--write regenerates it)
//   bun tools/modern-toolchain/check.ts legacy    no removed legacy tool in CI, scripts or container files
//   bun tools/modern-toolchain/check.ts userland  every adopted CLI runs `--version` on every node of cluster/build.toml (--local: and on this machine)
//   bun tools/modern-toolchain/check.ts git-nodes node git settings and long-lived checkouts registered for `git maintenance (--apply sets them)
//   bun tools/modern-toolchain/check.ts ssh       this machine: every node and alias of cluster/build.toml has the mesh-first route probe, ssh -G shows no agent forwarding,
//                                                 identity-only keys of an allowed type and the post-quantum first key exchange
//   bun tools/modern-toolchain/check.ts container Dockerfile builder tag = rust-toolchain.toml channel, every workspace member copied into the build
//   bun tools/modern-toolchain/check.ts publish   published crates (closure of product.toml crates_io_publish_order, read from cargo metadata)
//                                                 package at most `package_budget_bytes` of steps.toml (cargo package --list); an npm package without
//                                                 `files` or .npmignore may track at most the same
import { dirname, join } from "node:path";

const root = join(import.meta.dir, "..", "..");
type Steps = {
  tracked_binary?: { path: string; reason: string }[];
  legacy?: { pattern: string; replacement: string; scope: string[] }[];
  userland?: { bin: string; replaces: string; status: "adopted" | "rejected"; min_version?: string }[];
  dockerignore?: { always: string[] };
  package_budget_bytes?: number;
  ssh_audit?: { forbidden_probe?: string; first_kex?: string; key_types?: string[]; expect?: Record<string, string> };
  git_nodes?: { checkout_roots: string[]; config: Record<string, string> };
};
const steps = Bun.TOML.parse(await Bun.file(join(import.meta.dir, "steps.toml")).text()) as Steps;

const git = async (...args: string[]) => {
  const run = Bun.spawn(["git", "-C", root, ...args], { stdout: "pipe", stderr: "pipe" });
  const [out, code] = await Promise.all([new Response(run.stdout).text(), run.exited]);
  if (code !== 0) throw new Error(`git ${args.join(" ")} exited ${code}`);
  return out.split("\n").filter(Boolean);
};

const problems: string[] = [];

async function ignore() {
  for (const path of await git("ls-files", "-ci", "--exclude-standard")) problems.push(`tracked but ignored: ${path}`);
  const allowed = (steps.tracked_binary ?? []).map((entry) => entry.path);
  const output = /(^|\/)(target|node_modules|\.venv|__pycache__|\.gradle|\.kotlin|\.wrangler|\.next)\/|\.(exe|dll|pdb|o|obj|rlib|pyc|class)$/;
  for (const path of await git("ls-files")) if (output.test(path) && !allowed.includes(path)) problems.push(`tracked build output: ${path}`);
  const tracked = new Set(await git("ls-files"));
  if (tracked.has("Dockerfile")) {
    const expected = await dockerignore();
    const path = join(root, ".dockerignore");
    if (process.argv.includes("--write")) await Bun.write(path, expected);
    else if (!tracked.has(".dockerignore")) problems.push("Dockerfile without .dockerignore (run: check.ts ignore --write)");
    else if ((await Bun.file(path).text()) !== expected) problems.push(".dockerignore differs from the generated set (run: check.ts ignore --write)");
  }
}

// gitignore pattern -> dockerignore pattern: a pattern without a slash matches at any depth in git, so it takes `**/`;
// a leading or inner slash anchors it in both; docker has no trailing-slash rule, and the last matching line wins in both.
function dockerPattern(line: string) {
  const negated = line.startsWith("!");
  const body = negated ? line.slice(1) : line;
  const anchored = body.startsWith("/") || body.replace(/\/$/, "").includes("/");
  const plain = body.replace(/^\//, "").replace(/\/$/, "");
  return `${negated ? "!" : ""}${anchored ? plain : `**/${plain}`}`;
}

async function dockerignore() {
  const lines = ["# Generated by tools/modern-toolchain/check.ts ignore --write from steps.toml [dockerignore] and .gitignore; do not edit."];
  const seen = new Set<string>();
  const push = (line: string) => {
    if (!seen.has(line)) {
      seen.add(line);
      lines.push(line);
    }
  };
  for (const entry of steps.dockerignore?.always ?? []) push(entry);
  for (const raw of (await Bun.file(join(root, ".gitignore")).text()).split("\n")) {
    const line = raw.trim();
    if (line && !line.startsWith("#")) push(dockerPattern(line));
  }
  return `${lines.join("\n")}\n`;
}

async function legacy() {
  const files = await git("ls-files");
  for (const rule of steps.legacy ?? []) {
    const pattern = new RegExp(rule.pattern);
    for (const path of files) {
      if (path === "tools/modern-toolchain/steps.toml" || path === "tools/modern-toolchain/check.ts" || !rule.scope.some((scope) => path === scope || path.startsWith(`${scope}/`))) continue;
      const text = await Bun.file(join(root, path)).text().catch(() => "");
      text.split("\n").forEach((line, index) => {
        if (pattern.test(line)) problems.push(`${path}:${index + 1}: ${line.trim().slice(0, 100)} -> use ${rule.replacement}`);
      });
    }
  }
}

async function userland() {
  const adopted = (steps.userland ?? []).filter((entry) => entry.status === "adopted");
  const targets: { name: string; argv: (bin: string) => string[] }[] = [];
  if (process.argv.includes("--local")) targets.push({ name: "local", argv: (bin: string) => [bin, "--version"] });
  const build = Bun.TOML.parse(await Bun.file(join(root, "cluster", "build.toml")).text()) as { hosts?: Record<string, { ssh?: string }> };
  for (const [name, host] of Object.entries(build.hosts ?? {})) {
    const target = host.ssh ?? name;
    targets.push({ name: target, argv: (bin: string) => ["ssh", "-o", "BatchMode=yes", target, `${bin} --version`] });
  }
  for (const target of targets) {
    for (const entry of adopted) {
      const run = Bun.spawn(target.argv(entry.bin), { stdout: "pipe", stderr: "pipe", stdin: "ignore" });
      const [out, err, code] = await Promise.all([new Response(run.stdout).text(), new Response(run.stderr).text(), run.exited]);
      const version = (out || err).split("\n").find((line) => line.trim())?.trim().slice(0, 80) ?? "";
      const found = /(\d+)\.(\d+)\.(\d+)/.exec(version)?.slice(1).map(Number);
      const wanted = entry.min_version?.split(".").map(Number);
      const older = found && wanted && ((found[0] - wanted[0] || found[1] - wanted[1] || found[2] - wanted[2]) < 0);
      if (code === 0 && wanted && !found) problems.push(`${target.name}: ${entry.bin} version not readable from: ${version}`);
      else if (older) problems.push(`${target.name}: ${entry.bin} ${found.join(".")} is older than ${entry.min_version}`);
      if (code !== 0) problems.push(`${target.name}: ${entry.bin} --version failed (replaces ${entry.replaces}): ${version}`);
      else console.log(`${target.name.padEnd(6)} ${entry.bin.padEnd(7)} ${version}`);
    }
  }
}

async function gitNodes() {
  const apply = process.argv.includes("--apply");
  const build = Bun.TOML.parse(await Bun.file(join(root, "cluster", "build.toml")).text()) as { hosts?: Record<string, { ssh?: string; work: string }> };
  const wanted = steps.git_nodes?.config ?? {};
  for (const [name, host] of Object.entries(build.hosts ?? {})) {
    const target = host.ssh ?? name;
    const run = async (script: string) => {
      const proc = Bun.spawn(["ssh", "-o", "BatchMode=yes", target, script], { stdout: "pipe", stderr: "pipe", stdin: "ignore" });
      const [out, code] = await Promise.all([new Response(proc.stdout).text(), proc.exited]);
      return { out: out.trim(), code };
    };
    for (const [key, value] of Object.entries(wanted)) {
      const current = (await run(`git config --global --get ${key}`)).out;
      if (current.toLowerCase() === value.toLowerCase()) continue;
      if (apply) await run(`git config --global ${key} ${value}`);
      else problems.push(`${target}: git config ${key} is "${current}", wanted "${value}"`);
    }
    const roots = (steps.git_nodes?.checkout_roots ?? []).flatMap((root) => [`${host.work}/${root}`, `"$HOME/${root}"`]);
    const found = (await run(`for r in ${roots.map((entry) => (entry.startsWith('"') ? entry : `'${entry}'`)).join(" ")}; do for d in "$r"/*/; do [ -e "$d/.git" ] && realpath "\${d%/}"; done; done 2>/dev/null | sort -u`)).out.split("\n").filter(Boolean);
    const registered = (await run("git config --global --get-all maintenance.repo")).out.split("\n");
    for (const checkout of found) {
      if (registered.includes(checkout)) continue;
      if (apply) await run(`git -c safe.directory='${checkout}' -C '${checkout}' maintenance register; git -c safe.directory='${checkout}' -C '${checkout}' commit-graph write --reachable --changed-paths`);
      else problems.push(`${target}: ${checkout} is not registered for git maintenance`);
    }
    if (apply && found.length) await run(`git -c safe.directory='${found[0]}' -C '${found[0]}' maintenance start`);
    console.log(`${target}: ${found.length} long-lived checkouts, ${Object.keys(wanted).length} settings checked`);
  }
}

async function sshAudit() {
  const build = Bun.TOML.parse(await Bun.file(join(root, "cluster", "build.toml")).text()) as { hosts?: Record<string, { ssh?: string; aliases?: string[] }> };
  const config = await Bun.file(join(process.env.HOME ?? process.env.USERPROFILE ?? "", ".ssh", "config")).text().catch(() => "");
  const probed = new Set(config.split("\n").flatMap((line) => (/^\s*Match\s+host\s+(\S+)\s+exec\s+".*route print/i.exec(line)?.[1] ?? "").split(",")).filter(Boolean));
  const probeCommand = steps.ssh_audit?.forbidden_probe ?? "";
  if (probeCommand && config.includes(probeCommand)) problems.push(`~/.ssh/config still probes the mesh with \`${probeCommand}\``);
  for (const [name, host] of Object.entries(build.hosts ?? {})) {
    for (const alias of new Set([host.ssh ?? name, name, ...(host.aliases ?? [])])) {
      if (!probed.has(alias)) problems.push(`${alias}: no mesh-first Match block with the route-table probe in ~/.ssh/config`);
    }
    const target = host.ssh ?? name;
    const run = Bun.spawnSync(["ssh", "-G", target], { stdout: "pipe", stderr: "pipe" });
    const effective = new Map(run.stdout.toString().split("\n").map((line) => line.trim()).map((line) => [line.slice(0, line.indexOf(" ")), line.slice(line.indexOf(" ") + 1)] as const));
    const expect = steps.ssh_audit?.expect ?? {};
    for (const [key, value] of Object.entries(expect)) if (effective.get(key) !== value) problems.push(`${target}: ssh -G ${key} is "${effective.get(key)}", wanted "${value}"`);
    const kex = effective.get("kexalgorithms")?.split(",")[0];
    if (steps.ssh_audit?.first_kex && kex !== steps.ssh_audit.first_kex) problems.push(`${target}: first key exchange is ${kex}, wanted ${steps.ssh_audit.first_kex}`);
    const identity = effective.get("identityfile");
    const fingerprint = identity ? Bun.spawnSync(["ssh-keygen", "-l", "-f", `${identity}.pub`], { stdout: "pipe", stderr: "pipe" }).stdout.toString() : "";
    const type = /\((\w+)\)\s*$/.exec(fingerprint.trim())?.[1];
    if (!steps.ssh_audit?.key_types?.includes(type ?? "")) problems.push(`${target}: identity key type is ${type ?? "unreadable"}, allowed ${steps.ssh_audit?.key_types?.join(", ")}`);
    else console.log(`${target.padEnd(4)} key ${type} kex ${kex} forwardagent ${effective.get("forwardagent")}`);
  }
}

async function container() {
  const tracked = new Set(await git("ls-files"));
  if (!tracked.has("Dockerfile")) return;
  const dockerfile = await Bun.file(join(root, "Dockerfile")).text();
  const channel = /channel\s*=\s*"(\d+\.\d+)\.\d+"/.exec(await Bun.file(join(root, "rust-toolchain.toml")).text())?.[1];
  const builder = /^FROM rust:([\w.]+)-alpine\b/m.exec(dockerfile)?.[1];
  if (!builder) problems.push("Dockerfile: no `FROM rust:<version>-alpine` builder stage");
  else if (builder !== channel) problems.push(`Dockerfile builds with rust:${builder} but rust-toolchain.toml pins ${channel}`);
  const copies = [...dockerfile.matchAll(/^COPY\s+(?:--\S+\s+)*(.+?)\s+\S+\s*$/gm)].map((match) => match[1]!.split(/\s+/)).flat();
  if (!copies.includes(".")) {
    const members = (Bun.TOML.parse(await Bun.file(join(root, "Cargo.toml")).text()) as { workspace?: { members?: string[] } }).workspace?.members ?? [];
    for (const top of new Set(members.map((member) => member.split("/")[0]!))) {
      if (!copies.some((source) => source === top || source.startsWith(`${top}/`))) problems.push(`Dockerfile does not copy workspace members under ${top}/ (cargo loads every member manifest)`);
    }
  }
  if (/^FROM\s+\S+:latest\b/m.test(dockerfile)) problems.push("Dockerfile: a stage uses the :latest tag");
}

async function publish() {
  const files = await git("ls-files");
  const product = Bun.TOML.parse(await Bun.file(join(root, "product.toml")).text()) as { crates_io_publish_order: string[] };
  const metadata = JSON.parse(Bun.spawnSync(["cargo", "metadata", "--format-version", "1", "--no-deps", "--locked"], { cwd: root, stderr: "inherit" }).stdout.toString()) as {
    packages: { name: string; manifest_path: string; publish: string[] | null; dependencies: { name: string; kind: string | null; path?: string }[] }[];
  };
  const members = new Map(metadata.packages.map((entry) => [entry.name, entry]));
  const closure = new Set<string>();
  const visit = (name: string) => {
    const member = members.get(name);
    if (!member || closure.has(name)) return;
    closure.add(name);
    for (const dependency of member.dependencies) if (dependency.kind !== "dev" && dependency.path) visit(dependency.name);
  };
  product.crates_io_publish_order.forEach(visit);
  const budget = steps.package_budget_bytes ?? 1_048_576;
  for (const name of closure) {
    const member = members.get(name);
    if (!member) continue;
    const dir = dirname(member.manifest_path);
    const list = Bun.spawnSync(["cargo", "package", "--list", "--offline", "--allow-dirty", "-p", name], { cwd: root, stderr: "pipe" });
    if (list.exitCode !== 0) {
      problems.push(`crate ${name}: cargo package --list failed: ${list.stderr.toString().trim().split("\n").at(-1)}`);
      continue;
    }
    let bytes = 0;
    for (const file of list.stdout.toString().split("\n").filter(Boolean)) bytes += (await Bun.file(join(dir, file)).stat().catch(() => ({ size: 0 }))).size;
    console.log(`crate ${name}: ${bytes} B packaged`);
    if (bytes > budget) problems.push(`crate ${name}: ${bytes} B packaged exceeds ${budget}; add package.include or package.exclude`);
  }
  for (const path of files.filter((entry) => entry.endsWith("package.json"))) {
    const manifest = JSON.parse(await Bun.file(join(root, path)).text().catch(() => "{}")) as { private?: boolean; name?: string; files?: unknown };
    if (!manifest.name || manifest.private || /\/(src|schemas|templates|fixtures)\//.test(path)) continue;
    if (manifest.files || files.includes(path.replace("package.json", ".npmignore"))) continue;
    const folder = path.replace(/package\.json$/, "");
    let bytes = 0;
    for (const file of files.filter((entry) => entry.startsWith(folder))) bytes += (await Bun.file(join(root, file)).stat().catch(() => ({ size: 0 }))).size;
    console.log(`npm ${manifest.name}: ${bytes} B tracked, no files field or .npmignore`);
    if (bytes > budget) problems.push(`npm package ${manifest.name}: ${bytes} B tracked exceeds ${budget} and has no files field or .npmignore (${path})`);
  }
}

const command = process.argv[2];
if (command === "ignore") await ignore();
else if (command === "legacy") await legacy();
else if (command === "userland") await userland();
else if (command === "publish") await publish();
else if (command === "container") await container();
else if (command === "ssh") await sshAudit();
else if (command === "git-nodes") await gitNodes();
else {
  console.error("usage: check.ts ignore [--write] | legacy | userland [--local] | container | ssh | publish | git-nodes [--apply]");
  process.exit(2);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
console.log(`${command}: ok`);
