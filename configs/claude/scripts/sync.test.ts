import { describe, expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "./lib.ts";
import { buildUnifiedInstructions } from "./sync.ts";

describe("buildUnifiedInstructions", () => {
  const out = buildUnifiedInstructions();

  test("starts with the generated-file header", () => {
    expect(out.startsWith("<!-- Generated by ~/.claude/scripts/sync.ts")).toBe(
      true,
    );
    expect(out.split("\n")[1]).toBe("");
  });

  test("includes the trimmed CLAUDE.md content", () => {
    const claudeMd = join(REPO_ROOT, "CLAUDE.md");
    if (!existsSync(claudeMd)) return;
    const body = readFileSync(claudeMd, "utf8").trim();
    expect(out).toContain(body.replace(/\n{3,}/g, "\n\n"));
  });

  test("never contains runs of three newlines and ends with a newline", () => {
    expect(out).not.toMatch(/\n{3,}/);
    expect(out.endsWith("\n")).toBe(true);
  });

  test("memory sections use absolute-style links for relative .md files", () => {
    const sections = out.match(/^## Memory \(.+\)$/gm) ?? [];
    for (const s of sections) {
      const proj = s.slice("## Memory (".length, -1);
      expect(existsSync(join(REPO_ROOT, "projects", proj, "memory"))).toBe(
        true,
      );
    }
    expect(out).not.toMatch(/\]\((?!https?:|file:|\/|~)[^)#\s]+\.md\)/);
  });
});
