// Renders the model, constants, ioctls and syscalls as TypeScript source. Output is a pure function
// of its input: sorted where the input order is not meaningful, no timestamps, LF line endings.
import { type Constant } from "./constants.ts";
import { type IoctlDef } from "./ioctls.ts";
import { type EnumDef, type FieldDef, type FieldType, type Model, type RecordDef, type Scalar } from "./model.ts";
import { type SyscallTable } from "./syscalls.ts";

export interface Provenance {
  kernelTag: string;
  kernelCommit: string;
  arch: string;
}

const GENERATOR = "packages/linux-types/gen/gen.ts";

export function banner(p: Provenance): string {
  const commit = p.kernelCommit ? ` (${p.kernelCommit})` : "";
  return `// Generated by ${GENERATOR} from the Linux ${p.kernelTag} UAPI headers${commit}, arch ${p.arch}. Do not edit.\n`;
}

const MAX_SAFE = BigInt(Number.MAX_SAFE_INTEGER);

export function literal(value: bigint): string {
  return value >= -MAX_SAFE && value <= MAX_SAFE ? value.toString() : `${value}n`;
}

const BIGINT_SCALARS = new Set<Scalar>(["i64", "u64", "ptr"]);

function tsScalar(scalar: Scalar): string {
  if (BIGINT_SCALARS.has(scalar)) return "bigint";
  return scalar === "bool" ? "boolean" : "number";
}

function tsType(type: FieldType): string {
  switch (type.k) {
    case "scalar":
      return tsScalar(type.t);
    case "bits":
      return BIGINT_SCALARS.has(type.t) ? "bigint" : "number";
    case "bytes":
      return "Uint8Array";
    case "record":
      return type.key;
    case "inline":
      return `{ ${type.rec.fields.map((field) => `${field.name}: ${tsType(field.type)}`).join("; ")} }`;
    case "array": {
      if (type.of.k === "scalar" && type.of.t === "char") return "string";
      if (type.of.k === "scalar" && type.of.t === "u8") return "Uint8Array";
      if (type.of.k === "scalar" && type.of.t === "i8") return "Int8Array";
      const element = tsType(type.of);
      return `${element}[]`;
    }
  }
}

function descriptor(type: FieldType, last: boolean): string {
  switch (type.k) {
    case "scalar":
      return JSON.stringify(type.t);
    case "bits":
      return `bits(${JSON.stringify(type.t)}, ${type.bit}, ${type.n})`;
    case "bytes":
      return `bytes(${type.n})`;
    case "record":
      return `() => ${type.key}`;
    case "inline":
      return inlineLayout(type.rec);
    case "array":
      if (type.n === 0 && last) return `flex(${descriptor(type.of, false)})`;
      return `[${descriptor(type.of, false)}, ${type.n}]`;
  }
}

function fieldRows(fields: FieldDef[]): string[] {
  return fields.map((field, index) => `[${JSON.stringify(field.name)}, ${field.offset}, ${descriptor(field.type, index === fields.length - 1)}]`);
}

function inlineLayout(record: RecordDef): string {
  return `layout("", ${record.size}, ${record.align}, [${fieldRows(record.fields).join(", ")}]${record.union ? ", true" : ""})`;
}

function interfaceBody(record: RecordDef): string {
  return record.fields.map((field) => `  ${field.name}: ${tsType(field.type)};\n`).join("");
}

export function emitStructs(model: Model, p: Provenance): string {
  let out = banner(p);
  out += 'import { bits, bytes, flex, layout } from "../runtime/layout.ts";\n\n';
  out += "// struct_<tag>, union_<tag>: record with that tag. typedef_<name>: the anonymous record behind a\n";
  out += "// typedef, or an alias of the record the typedef names. Anonymous members are keys _anon0, _anon1, ...\n\n";
  const keys = [...model.records.keys()].sort();
  for (const key of keys) {
    const record = model.records.get(key) as RecordDef;
    const note = record.fromLibcStub ? ", declared by the libc stub the generator supplies (same ABI as glibc)" : "";
    out += `/** ${record.cname}: ${record.size} bytes, align ${record.align}${note} */\n`;
    out += `export interface ${key} {\n${interfaceBody(record)}}\n`;
    out += `export const ${key} = layout<${key}>(${JSON.stringify(record.cname)}, ${record.size}, ${record.align}, [\n`;
    out += fieldRows(record.fields).map((row) => `  ${row},\n`).join("");
    out += `]${record.union ? ", true" : ""});\n\n`;
  }
  for (const alias of [...model.aliases.keys()].sort()) {
    const target = model.aliases.get(alias) as string;
    if (!model.records.has(target)) continue;
    out += `export type ${alias} = ${target};\nexport const ${alias} = ${target};\n`;
  }
  return out;
}

export function emitEnums(model: Model, p: Provenance): string {
  let out = banner(p);
  out += "// enum_<tag> objects (and typedef_<name> for typedef'd enums). Every enumerator is also a constant\n// exported from constants.ts.\n\n";
  for (const key of [...model.enums.keys()].sort()) {
    const definition = model.enums.get(key) as EnumDef;
    out += `/** ${definition.cname} */\n`;
    out += `export const ${key} = { ${definition.values.map((entry) => `${entry.name}: ${literal(entry.value)}`).join(", ")} } as const;\n`;
    out += `export type ${key} = (typeof ${key})[keyof typeof ${key}];\n`;
  }
  for (const alias of [...model.aliases.keys()].sort()) {
    const target = model.aliases.get(alias) as string;
    if (!model.enums.has(target)) continue;
    out += `export const ${alias} = ${target};\nexport type ${alias} = ${target};\n`;
  }
  return out;
}

export function emitConstants(constants: Constant[], p: Provenance): string {
  let out = banner(p);
  out += "// Integer constants: object-like macros the compiler evaluated, then enumerators. Values above 2^53\n// are bigint. Ioctl requests are in ioctls.ts and syscall numbers in syscalls.ts.\n";
  const macros = constants.filter((constant) => constant.header !== "");
  const headers = [...new Set(macros.map((constant) => constant.header))].sort();
  for (const header of headers) {
    out += `\n// ${header}\n`;
    for (const constant of macros.filter((candidate) => candidate.header === header)) out += `export const ${constant.name} = ${literal(constant.value)};\n`;
  }
  const enumerators = constants.filter((constant) => constant.header === "");
  let current: string | undefined;
  for (const constant of enumerators) {
    if (constant.enumName !== current) {
      current = constant.enumName;
      out += `\n// ${current === "(anon)" ? "anonymous enum" : current}\n`;
    }
    out += `export const ${constant.name} = ${literal(constant.value)};\n`;
  }
  return out;
}

export function emitIoctls(ioctls: IoctlDef[], p: Provenance): string {
  let out = banner(p);
  const used = [...new Set(ioctls.map((entry) => entry.recordKey).filter((key): key is string => key !== null))].sort();
  out += 'import { ioctlDef } from "../runtime/ioctl.ts";\n';
  if (used.length > 0) out += `import { ${used.join(", ")} } from "./structs.ts";\n`;
  out += "\n// Request numbers decoded into dir/type/nr/size, with the argument layout when the macro names a struct or union.\n";
  out += "// Legacy requests (plain numbers: dir 0, size 0) get their argument from tty_ioctl(4), not from the headers:\n";
  out += `//   ${ioctls.filter((entry) => entry.legacy && entry.argType).map((entry) => entry.name).join(", ")}\n`;
  out += "export const ioctls = {\n";
  for (const entry of ioctls) {
    const arg = entry.recordKey ? `, ${JSON.stringify(entry.argType)}, () => ${entry.recordKey}` : entry.argType ? `, ${JSON.stringify(entry.argType)}` : "";
    out += `  ${entry.name}: ioctlDef(${entry.request}, ${entry.dir}, ${entry.type}, ${entry.nr}, ${entry.size}${arg}),\n`;
  }
  out += "} as const;\n\nexport type IoctlName = keyof typeof ioctls;\n";
  return out;
}

export function emitSyscalls(table: SyscallTable, p: Provenance): string {
  let out = banner(p);
  out += `// Native syscall numbers of ${p.arch} (the __NR_* macros of asm/unistd.h).\n`;
  out += "export const syscalls = {\n";
  for (const entry of table.syscalls) out += `  ${entry.name}: ${entry.number},\n`;
  out += "} as const;\n\nexport type SyscallName = keyof typeof syscalls;\n\n";
  out += "// Number to name; where two names share a number the first by name order is listed.\n";
  out += "export const syscallNames: Readonly<Record<number, SyscallName | undefined>> = {\n";
  const seen = new Set<number>();
  for (const entry of [...table.syscalls].sort((a, b) => a.number - b.number || a.name.localeCompare(b.name))) {
    if (seen.has(entry.number)) continue;
    seen.add(entry.number);
    out += `  ${entry.number}: ${JSON.stringify(entry.name)},\n`;
  }
  out += "};\n";
  return out;
}

export interface MetaCounts {
  [name: string]: number;
}

export function emitMeta(p: Provenance, counts: MetaCounts, headers: { included: number; excluded: { header: string; reason: string }[] }): string {
  let out = banner(p);
  out += "export const meta = {\n";
  out += `  kernelTag: ${JSON.stringify(p.kernelTag)},\n  kernelCommit: ${JSON.stringify(p.kernelCommit)},\n  arch: ${JSON.stringify(p.arch)},\n  generator: ${JSON.stringify(GENERATOR)},\n`;
  out += "  counts: {\n";
  for (const name of Object.keys(counts).sort()) out += `    ${name}: ${counts[name]},\n`;
  out += "  },\n";
  out += `  headersIncluded: ${headers.included},\n  headersExcluded: [\n`;
  for (const entry of headers.excluded) out += `    [${JSON.stringify(entry.header)}, ${JSON.stringify(entry.reason)}],\n`;
  out += "  ],\n} as const;\n";
  return out;
}

export function emitIndex(p: Provenance): string {
  let out = banner(p);
  for (const file of ["structs", "enums", "constants", "ioctls", "syscalls", "meta"]) out += `export * from "./${file}.ts";\n`;
  return out;
}
