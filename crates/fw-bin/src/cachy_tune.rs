//! CachyOS Rust & C++ Performance Tuning Engine (`fw tune`)
//! Modeled on `CachyOS/chwd` (v1.25.0, Rust), `CachyOS/scx-manager` (v1.16.0, C++23 + Corrosion),
//! `CachyOS/CachyOS-Settings` (`70-cachyos-settings.conf`), `CachyOS/sysctl-manager`, and `CachyOS/ananicy-rules`.

use crate::abliterate::{run_biprojected_math, RowNormalization};
use crate::ml_engine::run_lora_training;
use fw_compute::detect_hardware_profile;
use fw_ggml::{dot_q8_0, quantize_q8_0};
use serde_json::{json, Value};
use std::fs;
use std::path::Path;
use std::time::Instant;

/// Official `CachyOS/CachyOS-Settings` (`usr/lib/sysctl.d/70-cachyos-settings.conf`) tuning table.
pub const CACHYOS_SYSCTL_ENTRIES: &[(&str, &str, &str)] = &[
    ("vm.swappiness", "100", "Equal IO cost with zram swap"),
    ("vm.vfs_cache_pressure", "50", "Retain VFS dentry/inode cache longer"),
    ("vm.dirty_ratio", "10", "Scale dirty writeback ratio for fast NVMe"),
    ("vm.dirty_background_ratio", "3", "Start background flusher early"),
    ("vm.page-cluster", "0", "Disable swap readahead for zram/NVMe"),
    ("kernel.nmi_watchdog", "0", "Disable NMI watchdog overhead"),
    ("kernel.unprivileged_userns_clone", "1", "Allow unprivileged container/sandbox namespaces"),
    ("kernel.kptr_restrict", "2", "Restrict kernel pointer exposure"),
    ("net.core.netdev_max_backlog", "4096", "Increase netdev receive queue"),
    ("fs.file-max", "2097152", "Raise system open file descriptor limit"),
];

pub fn render_sysctl_conf() -> String {
    let mut out = String::from("# Generated by fw tune sysctl (CachyOS 70-cachyos-settings.conf parity)\n");
    for &(k, v, comment) in CACHYOS_SYSCTL_ENTRIES {
        out.push_str(&format!("# {comment}\n{k} = {v}\n"));
    }
    out
}

