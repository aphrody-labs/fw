fn site_identity(config: &Config) -> Result<Site> {
    let aphrody = read_toml(&config.root.join("aphrody/product.toml"))?;
    let docs_url = aphrody
        .get("urls")
        .and_then(|urls| urls.get("docs"))
        .and_then(toml::Value::as_str)
        .ok_or_else(|| anyhow!("aphrody/product.toml [urls].docs is missing"))?;
    let fw = read_toml(&config.root.join("product.toml"))?;
    let repository = fw
        .get("repository")
        .and_then(toml::Value::as_str)
        .unwrap_or_default()
        .to_owned();
    let organization = fw
        .get("organization")
        .and_then(toml::Value::as_str)
        .unwrap_or("aphrody-labs")
        .to_owned();
    let url = config
        .site
        .clone()
        .unwrap_or_else(|| docs_url.to_owned())
        .trim_end_matches('/')
        .to_owned();
    Ok(Site {
        url,
        name: "Aphrody docs".to_owned(),
        tagline: "Reference for fw, Aphrody and ay, generated from the code".to_owned(),
        repository,
        organization,
    })
}

/// The host of the fw edge Worker (installer scripts), read from the route pattern of cloudflare/wrangler.jsonc.
fn edge_host(root: &Path) -> Result<String> {
    let text = std::fs::read_to_string(root.join("cloudflare/wrangler.jsonc"))
        .context("cloudflare/wrangler.jsonc")?;
    text.lines()
        .filter(|line| !line.trim_start().starts_with("//"))
        .find_map(|line| {
            let rest = line.split_once("\"pattern\"")?.1;
            let start = rest.find('"')? + 1;
            let end = rest[start..].find('"')? + start;
            Some(rest[start..end].to_owned())
        })
        .ok_or_else(|| anyhow!("no route pattern in cloudflare/wrangler.jsonc"))
}

fn colors(config: &Config) -> Result<(String, String, String)> {
    let output = std::process::Command::new(&config.m3)
        .arg("css")
        .current_dir(&config.root)
        .output()
        .with_context(|| format!("cannot run `{} css`", config.m3))?;
    if !output.status.success() {
        bail!(
            "`{} css` failed: {}",
            config.m3,
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let table = read_toml(&config.root.join("product.toml"))?;
    let brand = table.get("brand").and_then(toml::Value::as_table);
    let text = |key: &str| {
        brand
            .and_then(|brand| brand.get(key))
            .and_then(toml::Value::as_str)
            .unwrap_or_default()
            .to_owned()
    };
    Ok((
        normalize_colors(&String::from_utf8_lossy(&output.stdout).replace("\r\n", "\n")),
        text("seed"),
        text("variant"),
    ))
}

/// Starlight always sets `data-theme` on the root element, so the `prefers-color-scheme` block of fw-m3 would only fight an explicit light
/// choice. Drop it and let the light roles also answer to `data-theme="light"`.
fn normalize_colors(css: &str) -> String {
    let mut out = String::new();
    let mut skipping = false;
    let mut depth = 0i32;
    for line in css.lines() {
        if !skipping && line.starts_with("@media (prefers-color-scheme: dark)") {
            skipping = true;
        }
        if skipping {
            depth += line.matches('{').count() as i32 - line.matches('}').count() as i32;
            if depth <= 0 {
                skipping = false;
                depth = 0;
            }
            continue;
        }
        if line.starts_with(":root {") {
            out.push_str(":root, :root[data-theme=\"light\"] {\n");
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

pub fn build(config: &Config) -> Result<Bundle> {
    let root = config.root.as_path();
    let site = site_identity(config)?;
    let cli = read_cli(&config.fw, root)?;
    let tools = read_mcp_tools(&config.bun, root)?;
    let crates = read_crates(root)?;
    let targets = read_release_targets(root)?;
    let snapshot = config.out_dir().join(SNAPSHOT);
    let (manifest_text, manifest) =
        read_release_manifest(&snapshot, config.live, RELEASE_MANIFEST_URL)?;
    let surfaces = read_api_surfaces(&config.fw, root)?;
    let fw_product = read_toml(&root.join("product.toml"))?;
    let aphrody_product = read_toml(&root.join("aphrody/product.toml"))?;
    let ay_config = read_toml(&root.join("ay/ay.toml"))?;
    let contracts = std::fs::read_to_string(root.join("docs/research/api-contracts-2026-11-21.md"))
        .unwrap_or_default();
    let (color_css, seed, variant) = colors(config)?;
    let install_host = edge_host(root)?;

    let data = render::Data {
        site: &site,
        cli: &cli,
        tools: &tools,
        crates: &crates,
        targets: &targets,
        manifest: &manifest,
        surfaces: &surfaces,
        fw_product: &fw_product,
        aphrody_product: &aphrody_product,
        ay: &ay_config,
        contracts: &contracts,
        install_host: &install_host,
    };
    let pages = render::all_pages(&data);
    validate(&pages)?;

    let mut files: BTreeMap<String, String> = BTreeMap::new();
    for page in &pages {
        files.insert(
            format!("src/content/docs/{}.mdx", page_file(&page.slug)),
            render_mdx(page, &site, &pages),
        );
        files.insert(
            format!("public/{}", markdown_twin_path(&page.slug)),
            render_markdown_twin(page, &site),
        );
    }
    files.insert(
        "src/generated/sidebar.json".to_owned(),
        render::sidebar(&pages) + "\n",
    );
    files.insert(
        "src/generated/site.json".to_owned(),
        serde_json::to_string_pretty(&json!({
            "generated": format!("generated by fw site from product.toml, aphrody/product.toml@{}", short_hash(&format!("{}{}{}", site.url, seed, variant))),
            "url": site.url,
            "title": site.name,
            "description": site.tagline,
            "repository": site.repository,
            "organization": site.organization,
            "seed": seed,
            "variant": variant,
            "ogImage": format!("{}/og.png", site.url),
            "ogImageAlt": format!("{} on a card in the brand color", site.name),
            "pages": pages.len(),
        }))? + "\n",
    );
    files.insert(
        "src/generated/colors.css".to_owned(),
        format!(
            "/* generated by fw site from `fw-m3 css` (product.toml [brand] seed {seed}, variant {variant})@{} */\n{color_css}",
            short_hash(&color_css)
        ),
    );
    files.insert(
        "public/og.svg".to_owned(),
        render::og_card(&site, &color_css, pages.len()),
    );
    files.insert("public/favicon.svg".to_owned(), render::favicon(&color_css));
    files.insert("public/robots.txt".to_owned(), render::robots(&site));
    files.insert(
        "public/sitemap.xml".to_owned(),
        render::sitemap(&site, &pages),
    );
    files.insert(
        "public/llms.txt".to_owned(),
        render::llms_txt(&site, &pages),
    );
    files.insert(
        "public/llms-full.txt".to_owned(),
        render::llms_full(&site, &pages),
    );
    if config.live {
        files.insert(SNAPSHOT.to_owned(), manifest_text);
    }
    Ok(Bundle { files, pages })
}

fn validate(pages: &[Page]) -> Result<()> {
    let mut slugs = BTreeSet::new();
    let mut titles = BTreeSet::new();
    let mut descriptions = BTreeSet::new();
    for page in pages {
        if !slugs.insert(page.slug.clone()) {
            bail!("duplicate slug {}", page.slug);
        }
        if !titles.insert(page.title.clone()) {
            bail!("duplicate title `{}` ({})", page.title, page.slug);
        }
        if !descriptions.insert(page.description.clone()) {
            bail!("duplicate description on {}", page.slug);
        }
        let title_length = page.title.chars().count();
        if title_length > 48 {
            bail!(
                "title of {} is {title_length} characters; keep it under 49 so the suffix fits in 60",
                page.slug
            );
        }
        let description_length = page.description.chars().count();
        if !(50..=160).contains(&description_length) {
            bail!(
                "description of {} is {description_length} characters; it must be 50 to 160",
                page.slug
            );
        }
    }
    Ok(())
}

fn page_file(slug: &str) -> String {
    if slug == "index" {
        "index".to_owned()
    } else if is_section(slug) {
        format!("{slug}/index")
    } else {
        slug.to_owned()
    }
}

fn is_section(slug: &str) -> bool {
    matches!(
        slug,
        "start" | "cli" | "mcp" | "api" | "crates" | "products" | "guides"
    )
}

fn markdown_twin_path(slug: &str) -> String {
    if slug == "index" {
        "index.md".to_owned()
    } else {
        format!("{slug}/index.md")
    }
}

fn render_mdx(page: &Page, site: &Site, all: &[Page]) -> String {
    let mut front = String::from("---\n");
    front.push_str(&format!("title: {}\n", yaml(&json!(page.title))));
    front.push_str(&format!(
        "description: {}\n",
        yaml(&json!(page.description))
    ));
    front.push_str(&format!(
        "generated: {}\n",
        yaml(&json!(format!(
            "generated by fw site from {}@{}",
            page.inputs, page.input_hash
        )))
    ));
    if let Some(splash) = &page.splash {
        front.push_str("template: splash\n");
        front.push_str(&format!("hero: {}\n", yaml(splash)));
    }
    if let Some(label) = &page.label {
        front.push_str(&format!("sidebar: {}\n", yaml(&json!({ "label": label }))));
    }
    let breadcrumbs: Vec<Value> = render::crumbs(page, all)
        .iter()
        .map(|(name, path)| json!({ "name": name, "path": path }))
        .collect();
    front.push_str(&format!("breadcrumbs: {}\n", yaml(&json!(breadcrumbs))));
    let graph = render::json_ld(page, site, all);
    front.push_str(&format!(
        "head: {}\n",
        yaml(&json!([{
            "tag": "script",
            "attrs": { "type": "application/ld+json" },
            "content": serde_json::to_string(&graph).unwrap_or_default()
        }]))
    ));
    front.push_str("---\n\n");
    front.push_str(page.body.trim_end());
    front.push('\n');
    front
}

fn render_markdown_twin(page: &Page, site: &Site) -> String {
    format!(
        "{MARKDOWN_TWIN_MARKER}\n# {}\n\n> {}\n\nSource: {}{}\n\n{}\n",
        page.title,
        page.description,
        site.url,
        page.url_path(),
        page.markdown_body().trim_end()
    )
}

fn owned_on_disk(out: &Path) -> Result<BTreeSet<String>> {
    let mut found = BTreeSet::new();
    for dir in OWNED_DIRS {
        collect(&out.join(dir), out, &mut found)?;
    }
    for file in OWNED_FILES {
        if out.join(file).is_file() {
            found.insert((*file).to_owned());
        }
    }
    for dir in ["public"] {
        let mut all = BTreeSet::new();
        collect(&out.join(dir), out, &mut all)?;
        for file in all {
            if file.ends_with(".md") {
                found.insert(file);
            }
        }
    }
    Ok(found)
}

fn collect(dir: &Path, base: &Path, found: &mut BTreeSet<String>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(&path, base, found)?;
        } else {
            let relative = path
                .strip_prefix(base)?
                .to_string_lossy()
                .replace('\\', "/");
            found.insert(relative);
        }
    }
    Ok(())
}

fn is_generated_markdown(path: &Path) -> bool {
    std::fs::read_to_string(path)
        .map(|text| text.starts_with(MARKDOWN_TWIN_MARKER))
        .unwrap_or(false)
}

pub fn generate(config: &Config) -> Result<String> {
    let bundle = build(config)?;
    let out = config.out_dir();
    let on_disk = owned_on_disk(&out)?;
    let mut removed = 0usize;
    for stale in on_disk.difference(&bundle.files.keys().cloned().collect()) {
        let path = out.join(stale);
        if stale.starts_with("public/") && stale.ends_with(".md") && !is_generated_markdown(&path) {
            continue;
        }
        std::fs::remove_file(&path)?;
        removed += 1;
    }
    let mut written = 0usize;
    for (relative, content) in &bundle.files {
        let path = out.join(relative);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(content.as_str()) {
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, content)?;
        written += 1;
    }
    Ok(format!(
        "fw site gen: {} pages, {} files, {} written, {} removed ({})",
        bundle.pages.len(),
        bundle.files.len(),
        written,
        removed,
        out.display()
    ))
}

pub fn write_llms(config: &Config) -> Result<String> {
    let bundle = build(config)?;
    let out = config.out_dir();
    for name in ["public/llms.txt", "public/llms-full.txt"] {
        let path = out.join(name);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, &bundle.files[name])?;
    }
    Ok(format!(
        "fw site llms: {} pages indexed",
        bundle.pages.len()
    ))
}

/// Differences between the code and the files on disk. Empty means no drift.
pub fn check(config: &Config) -> Result<Vec<String>> {
    let bundle = build(config)?;
    let out = config.out_dir();
    let mut problems = Vec::new();
    for (relative, content) in &bundle.files {
        match std::fs::read_to_string(out.join(relative)) {
            Ok(existing) if existing == *content => {}
            Ok(_) => problems.push(format!("{relative} differs from the generated content")),
            Err(_) => problems.push(format!("{relative} is missing")),
        }
    }
    let expected: BTreeSet<&String> = bundle.files.keys().collect();
    for relative in owned_on_disk(&out)? {
        if expected.contains(&relative) {
            continue;
        }
        if relative.starts_with("public/")
            && relative.ends_with(".md")
            && !is_generated_markdown(&out.join(&relative))
        {
            continue;
        }
        problems.push(format!("{relative} is stale: nothing generates it"));
    }
    Ok(problems)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn description_is_cut_at_a_word_and_stays_under_the_limit() {
        let long = "word ".repeat(80);
        let fitted = fit_description(&long);
        assert!(fitted.chars().count() <= 160);
        assert!(fitted.ends_with('…'));
        assert!(!fitted.contains("wor…"));
        assert_eq!(fit_description("short   text"), "short text");
    }

    #[test]
    fn escaping_leaves_code_spans_alone_and_round_trips() {
        assert_eq!(
            esc("use `Vec<u8>` or <b>{x}</b>"),
            "use `Vec<u8>` or &lt;b&gt;&#123;x&#125;&lt;/b&gt;"
        );
        assert_eq!(unescape_mdx(&esc("<a> {b}")), "<a> {b}");
        assert_eq!(cell("a | b\nc"), "a \\| b c");
    }

    #[test]
    fn hash_is_stable_and_twelve_hex_digits() {
        assert_eq!(short_hash("fw"), short_hash("fw"));
        assert_ne!(short_hash("fw"), short_hash("fx"));
        assert_eq!(short_hash("fw").len(), 12);
    }

    #[test]
    fn sections_of_a_section_page_use_index_files() {
        assert_eq!(page_file("index"), "index");
        assert_eq!(page_file("cli"), "cli/index");
        assert_eq!(page_file("cli/ask"), "cli/ask");
        assert_eq!(markdown_twin_path("cli/ask"), "cli/ask/index.md");
        assert_eq!(markdown_twin_path("index"), "index.md");
    }

    #[test]
    fn colors_drop_the_media_block_and_answer_to_data_theme_light() {
        let css = ":root {\n  --a: 1;\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n    --a: 2;\n  }\n}\n:root[data-theme=\"dark\"] {\n  --a: 2;\n}\n";
        let out = normalize_colors(css);
        assert!(out.starts_with(":root, :root[data-theme=\"light\"] {"));
        assert!(!out.contains("@media"));
        assert!(out.contains(":root[data-theme=\"dark\"]"));
    }
}
