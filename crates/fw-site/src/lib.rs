#![forbid(unsafe_code)]
//! `fw site`: the docs site of the Aphrody stack, generated from code.
//!
//! `generate` writes MDX pages, the sidebar, theme colors, llms.txt, sitemap.xml, robots.txt and a markdown twin of every page
//! under `apps/docs`. `check` builds the same set in memory and reports every file that differs, is missing or is stale.
//! Every page carries a `generated` front-matter field: the inputs it came from and a short hash of them.

mod inputs;
mod render;

use anyhow::{Context, Result, anyhow, bail};
use serde_json::{Value, json};
