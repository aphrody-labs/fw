pub use inputs::*;

/// Directories and files of `apps/docs` that `fw site` owns. Anything under them that it does not produce is stale.
const OWNED_DIRS: &[&str] = &["src/content/docs", "src/generated"];
const OWNED_FILES: &[&str] = &[
    "public/llms.txt",
    "public/llms-full.txt",
    "public/robots.txt",
    "public/sitemap.xml",
    "public/og.svg",
    "public/favicon.svg",
];
const MARKDOWN_TWIN_MARKER: &str = "<!-- generated by fw site -->";
const RELEASE_MANIFEST_URL: &str = "https://releases.aphrody.com/manifest.json";
const SNAPSHOT: &str = "src/data/release-manifest.json";

#[derive(Debug, Clone)]
pub struct Config {
    pub root: PathBuf,
    pub out: PathBuf,
    pub fw: String,
    pub bun: String,
    pub m3: String,
    pub site: Option<String>,
    pub live: bool,
}

impl Config {
    pub fn new(root: PathBuf) -> Self {
        Self {
            out: PathBuf::from("apps/docs"),
            root,
            fw: "fw".to_owned(),
            bun: "bun".to_owned(),
            m3: "fw-m3".to_owned(),
            site: None,
            live: false,
        }
    }

    fn out_dir(&self) -> PathBuf {
        if self.out.is_absolute() {
            self.out.clone()
        } else {
            self.root.join(&self.out)
        }
    }
}

#[derive(Debug, Clone)]
pub enum Schema {
    Article,
    Software {
        name: String,
        version: String,
        systems: Vec<String>,
        download: String,
        repository: String,
    },
}

#[derive(Debug, Clone)]
pub struct Page {
    pub slug: String,
    pub title: String,
    pub description: String,
    pub section: String,
    pub body: String,
    pub body_md: Option<String>,
    pub inputs: String,
    pub input_hash: String,
    pub schema: Schema,
    pub label: Option<String>,
    pub splash: Option<Value>,
}

impl Page {
    pub fn new(slug: &str, title: &str, description: &str, section: &str, body: String) -> Self {
        Self {
            slug: slug.to_owned(),
            title: title.to_owned(),
            description: fit_description(description),
            section: section.to_owned(),
            body,
            body_md: None,
            inputs: String::new(),
            input_hash: String::new(),
            schema: Schema::Article,
            label: None,
            splash: None,
        }
    }

    pub fn sourced(mut self, inputs: &str, material: &str) -> Self {
        self.inputs = inputs.to_owned();
        self.input_hash = short_hash(material);
        self
    }

    pub fn label(mut self, label: &str) -> Self {
        self.label = Some(label.to_owned());
        self
    }

    pub fn url_path(&self) -> String {
        if self.slug == "index" {
            "/".to_owned()
        } else {
            format!("/{}/", self.slug)
        }
    }

    fn markdown_body(&self) -> String {
        let source = self.body_md.as_deref().unwrap_or(&self.body);
        unescape_mdx(source)
    }
}

pub struct Site {
    pub url: String,
    pub name: String,
    pub tagline: String,
    pub repository: String,
    pub organization: String,
}

pub fn short_hash(material: &str) -> String {
    let digest = Sha256::digest(material.as_bytes());
    digest
        .iter()
        .take(6)
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// Keep a meta description between 50 and 160 characters, cut at a word boundary.
pub fn fit_description(text: &str) -> String {
    let flat: String = text.split_whitespace().collect::<Vec<_>>().join(" ");
    let chars: Vec<char> = flat.chars().collect();
    if chars.len() <= 160 {
        return flat;
    }
    let mut cut: String = chars[..159].iter().collect();
    if let Some(space) = cut.rfind(' ') {
        cut.truncate(space);
    }
    let cut = cut.trim_end_matches([',', ';', ':', '.', ' ', '(']);
    format!("{cut}…")
}

/// Escape text for MDX: braces and angle brackets outside code spans.
pub fn esc(text: &str) -> String {
    let mut out = String::new();
    for (index, segment) in text.split('`').enumerate() {
        if index > 0 {
            out.push('`');
        }
        if index % 2 == 1 && text.matches('`').count().is_multiple_of(2) {
            out.push_str(segment);
        } else {
            for c in segment.chars() {
                match c {
                    '<' => out.push_str("&lt;"),
                    '>' => out.push_str("&gt;"),
                    '{' => out.push_str("&#123;"),
                    '}' => out.push_str("&#125;"),
                    _ => out.push(c),
                }
            }
        }
    }
    out
}

pub fn unescape_mdx(text: &str) -> String {
    text.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&#123;", "{")
        .replace("&#125;", "}")
}

/// A markdown table cell: one line, pipes escaped.
pub fn cell(text: &str) -> String {
    esc(&text.replace('\n', " ").replace('|', "\\|"))
}

pub fn code_cell(text: &str) -> String {
    if text.is_empty() {
        String::new()
    } else {
        format!(
            "`{}`",
            text.replace('\n', " ")
                .replace('|', "\\|")
                .replace('`', "'")
        )
    }
}

fn yaml(value: &Value) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "null".to_owned())
}

