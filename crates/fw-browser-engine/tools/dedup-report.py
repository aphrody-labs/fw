#!/usr/bin/env python3
"""docs/dedup.md from the per-upstream locks (before) and the unified Cargo.lock (after).
usage: dedup-report.py <monorepo> > docs/dedup.md"""
import sys, os, tomllib, json, glob, collections
mono = sys.argv[1]


def ext(path):
    d = tomllib.load(open(path, "rb"))
    v = collections.defaultdict(set)
    for p in d.get("package", []):
        if "source" in p:
            v[p["name"]].add(p["version"])
    return v


locks = sorted(glob.glob(os.path.join(mono, "upstream", "*", "Cargo.lock"))) + glob.glob(os.path.join(mono, "src", "agent-browser", "Cargo.lock"))
rows, union = [], collections.defaultdict(set)
for f in locks:
    v = ext(f)
    for n, s in v.items():
        union[n] |= s
    rows.append((os.path.relpath(f, mono), sum(len(s) for s in v.values()), sum(1 for s in v.values() if len(s) > 1)))
after = ext(os.path.join(mono, "Cargo.lock"))
ad = {n: sorted(s) for n, s in after.items() if len(s) > 1}
print("# Dedup report (generated by tools/dedup-report.py)\n")
print("Before = each upstream resolved alone (its own Cargo.lock); after = one `Cargo.lock` for the whole workspace.\n")
print("| lock | external packages | crates at >1 version |\n|---|---:|---:|")
for r in rows:
    print(f"| {r[0]} | {r[1]} | {r[2]} |")
print(f"| **sum of the upstreams** | {sum(r[1] for r in rows)} | {sum(r[2] for r in rows)} |")
print(f"| **union by crate** (what building them side by side would carry) | {sum(len(s) for s in union.values())} | {sum(1 for s in union.values() if len(s) > 1)} |")
print(f"| **after: unified Cargo.lock** | {sum(len(s) for s in after.values())} | {len(ad)} |\n")
rep = os.path.join(mono, "tools", "unify.report.json")
if os.path.exists(rep):
    r = json.load(open(rep))
    print(f"`tools/unify.py` raised {sum(r['edits'].values())} direct requirements on {len(r['target'])} crates to the newest line in the workspace.\n")
skip = os.path.join(mono, "tools", "unify.skip")
if os.path.exists(skip):
    print("Left on purpose (`tools/unify.skip`):\n")
    for l in open(skip):
        if l.strip():
            print("- " + l.strip())
    print()
print("Crates that live in the monorepo are path dependencies for every member (no git or crates.io self-reference); "
      "`[patch.crates-io]` points third-party dependents at the same copy.\n")
print("Most split crates still in the lock (transitive, need a parent upgrade):\n")
print("| crate | versions |\n|---|---|")
for n in sorted(ad, key=lambda n: -len(ad[n]))[:25]:
    print(f"| {n} | {', '.join(ad[n])} |")
