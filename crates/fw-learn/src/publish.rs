//! Writes the distilled rules where agents read them: a generated block in each product's AGENTS.md (and CLAUDE.md when it
//! exists), one full rules file per product, and the repository's `llms.txt` and `llms-full.txt`. Files are committed by path
//! onto origin/main through a temporary index, so the shared working tree is never touched.

use crate::distill::render;
use crate::products::{Product, Repo, git};
use crate::store::Store;
use anyhow::{Context, Result, bail};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

pub const BEGIN: &str = "<!-- learn:begin";
pub const END: &str = "<!-- learn:end -->";
const FULL_LIMIT: usize = 300 * 1024;
const GENERATED: &str = "Generated by fw learn";

pub struct Outcome {
    pub changed: Vec<String>,
    pub commit: Option<String>,
}

/// Replaces the block named `id` in `base`, or appends it.
pub fn replace_block(base: &str, id: &str, block: &str) -> String {
    let marker = format!("{BEGIN} {id} ");
    if let Some(start) = base.find(&marker)
        && let Some(relative_end) = base[start..].find(END)
    {
        let end = start + relative_end + END.len();
        return format!("{}{block}{}", &base[..start], &base[end..]);
    }
    let separator = if base.is_empty() || base.ends_with("\n\n") { "" } else if base.ends_with('\n') { "\n" } else { "\n\n" };
    format!("{base}{separator}{block}\n")
}

fn block(id: &str, repo: &Repo, body: &str) -> String {
    format!("{BEGIN} {id} (generated by fw learn from {}; do not edit) -->\n## Learned rules (fw learn)\n\n{body}{END}", repo.name)
}

pub fn strip_blocks(text: &str) -> String {
    let mut out = String::new();
    let mut inside = false;
    for line in text.lines() {
        if line.contains(BEGIN) {
            inside = true;
        }
        if !inside {
            out.push_str(line);
            out.push('\n');
        }
        if line.contains(END) {
            inside = false;
        }
    }
    format!("{}\n", out.trim_end())
}

/// The two review-banner lines an AGENTS.md demands at the top of README.md, quoted in backticks in its own text.
pub fn banner_lines(agents: &str) -> Option<[String; 2]> {
    let quoted: Vec<&str> = agents.split('`').skip(1).step_by(2).collect();
    let first = quoted.iter().find(|segment| segment.starts_with("> [!IMPORTANT]"))?;
    let second = quoted.iter().find(|segment| segment.starts_with("> Remove this line"))?;
    Some([(*first).to_owned(), (*second).to_owned()])
}

fn show(repo: &Path, path: &str) -> Option<String> {
    let output = Command::new("git").arg("-C").arg(repo).args(["show", &format!("origin/main:{path}")]).output().ok()?;
    output.status.success().then(|| String::from_utf8_lossy(&output.stdout).into_owned())
}

fn join(dir: &str, file: &str) -> String {
    if dir.is_empty() { file.to_owned() } else { format!("{dir}/{file}") }
}

/// Every file to write, as `(path, content)`, computed from the blobs of origin/main.
pub fn plan(store: &Store, repo: &Repo, products: &[Product]) -> Result<Vec<(String, String)>> {
    let mut files: Vec<(String, String)> = Vec::new();
    let mut learned: Vec<(String, String)> = Vec::new();
    for product in products {
        let compact = block(&product.id, repo, &render(store, &product.id, true)?);
        let mut targets = vec![join(&product.dir, "AGENTS.md")];
        let claude = join(&product.dir, "CLAUDE.md");
        if show(&repo.path, &claude).is_some() {
            targets.push(claude);
        }
        for target in targets {
            let base = show(&repo.path, &target).unwrap_or_else(|| format!("# {} agent contract\n", product.display));
            if let Some(lines) = banner_lines(&base) {
                let readme = join(&product.dir, "README.md");
                let current = show(&repo.path, &readme).unwrap_or_default();
                if !current.starts_with(&lines[0]) {
                    files.push((readme, format!("{}\n{}\n{current}", lines[0], lines[1])));
                }
            }
            files.push((target, replace_block(&base, &product.id, &compact)));
        }
        let full = format!("# Learned rules: {}\n\nGenerated by fw learn from the history of {}. Each bullet carries its evidence; regenerate with `fw learn publish`.\n\n{}", product.display, repo.name, render(store, &product.id, false)?);
        let path = format!("docs/knowledge/learned/{}.md", product.id);
        learned.push((path.clone(), full.clone()));
        files.push((path, full));
    }
    let (llms, llms_full) = llms(repo, products, &learned);
    for (path, content) in [("llms.txt", llms), ("llms-full.txt", llms_full)] {
        // A hand-written or site-generated file of the same name is never overwritten.
        if show(&repo.path, path).is_none_or(|current| current.contains(GENERATED)) {
            files.push((path.to_owned(), content));
        }
    }
    Ok(files)
}

fn llms(repo: &Repo, products: &[Product], learned: &[(String, String)]) -> (String, String) {
    let base_url = repo.slug.as_ref().map(|slug| format!("https://github.com/{slug}/blob/main/")).unwrap_or_default();
    let root = products.iter().find(|product| product.dir.is_empty()).unwrap_or(&products[0]);
    let mut text = format!("# {}\n\n> {}\n\nGenerated by fw learn from the history of {}. Read AGENTS.md first.\n\n## Agents\n\n", root.display, if root.description.is_empty() { "Repository of the Aphrody stack." } else { &root.description }, repo.name);
    for product in products {
        text.push_str(&format!("- [{} agent contract]({base_url}{}): rules and gates agents follow in this product\n", product.display, join(&product.dir, "AGENTS.md")));
    }
    text.push_str("\n## Products\n\n");
    for product in products {
        let note = if product.description.is_empty() { format!("{} product", product.display) } else { product.description.clone() };
        text.push_str(&format!("- [{}]({base_url}{}): {note}\n", product.display, join(&product.dir, "README.md")));
    }
    text.push_str("\n## Learned rules\n\n");
    for product in products {
        text.push_str(&format!("- [{}]({base_url}docs/knowledge/learned/{}.md): pitfalls, hot areas, coupling, CI and release state derived from history\n", product.display, product.id));
    }
    let docs: Vec<&Product> = products.iter().filter(|product| product.docs_url.starts_with("http") && !product.docs_url.contains("github.com")).collect();
    if !docs.is_empty() {
        text.push_str("\n## Docs\n\n");
        for product in docs {
            text.push_str(&format!("- [{} documentation]({}): command, tool and API reference\n", product.display, product.docs_url));
        }
    }
    let mut full = text.clone();
    for product in products {
        for (title, path) in [("agent contract", join(&product.dir, "AGENTS.md")), ("readme", join(&product.dir, "README.md"))] {
            if let Some(content) = show(&repo.path, &path) {
                full.push_str(&format!("\n---\n\n<!-- {} {title}: {path} -->\n\n{}", product.id, strip_blocks(&content)));
            }
        }
    }
    for (path, content) in learned {
        full.push_str(&format!("\n---\n\n<!-- {path} -->\n\n{content}"));
    }
    if full.len() > FULL_LIMIT {
        let cut = (0..=FULL_LIMIT).rev().find(|index| full.is_char_boundary(*index)).unwrap_or(0);
        full.truncate(cut);
        full.push_str("\n\n<!-- truncated at the size limit -->\n");
    }
    (text, full)
}

fn run(index: &Path, repo: &Path, args: &[&str], stdin: Option<&str>) -> Result<String> {
    let mut child = Command::new("git")
        .arg("-C")
        .arg(repo)
        .args(args)
        .env("GIT_INDEX_FILE", index)
        .stdin(if stdin.is_some() { Stdio::piped() } else { Stdio::null() })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .with_context(|| format!("spawn git {}", args.join(" ")))?;
    if let (Some(text), Some(mut pipe)) = (stdin, child.stdin.take()) {
        pipe.write_all(text.as_bytes()).context("write git stdin")?;
    }
    let output = child.wait_with_output().context("wait for git")?;
    if !output.status.success() {
        bail!("git {}: {}", args.join(" "), String::from_utf8_lossy(&output.stderr).trim());
    }
    Ok(String::from_utf8_lossy(&output.stdout).trim().to_owned())
}

/// Commits `files` onto origin/main by path through a temporary index and pushes it; retries when the push races another agent.
pub fn publish(repo: &Repo, build: &dyn Fn() -> Result<Vec<(String, String)>>, message: &str, push: bool) -> Result<Outcome> {
    let index: PathBuf = std::env::temp_dir().join(format!("fw-learn-index-{}", std::process::id()));
    let result = (|| {
        let mut last = String::new();
        for _attempt in 0..4 {
            git(&repo.path, &["fetch", "--quiet", "origin", "main"])?;
            let files = build()?;
            std::fs::remove_file(&index).ok();
            run(&index, &repo.path, &["read-tree", "origin/main"], None)?;
            let mut changed = Vec::new();
            for (path, content) in &files {
                if show(&repo.path, path).as_deref() == Some(content.as_str()) {
                    continue;
                }
                let mode = git(&repo.path, &["ls-tree", "origin/main", path]).ok().and_then(|line| line.split(' ').next().map(str::to_owned)).filter(|mode| !mode.is_empty()).unwrap_or_else(|| "100644".to_owned());
                let sha = run(&index, &repo.path, &["hash-object", "-w", "--stdin"], Some(content))?;
                run(&index, &repo.path, &["update-index", "--add", "--cacheinfo", &format!("{mode},{sha},{path}")], None)?;
                changed.push(path.clone());
            }
            if changed.is_empty() {
                return Ok(Outcome { changed, commit: None });
            }
            let tree = run(&index, &repo.path, &["write-tree"], None)?;
            if tree == git(&repo.path, &["rev-parse", "origin/main^{tree}"])? {
                return Ok(Outcome { changed: Vec::new(), commit: None });
            }
            let commit = run(&index, &repo.path, &["commit-tree", &tree, "-p", "origin/main", "-m", message], None)?;
            if !push {
                return Ok(Outcome { changed, commit: Some(commit) });
            }
            match git(&repo.path, &["push", "origin", &format!("{commit}:refs/heads/main")]) {
                Ok(_) => return Ok(Outcome { changed, commit: Some(commit) }),
                Err(error) => last = error.to_string(),
            }
        }
        bail!("push kept failing: {last}")
    })();
    std::fs::remove_file(&index).ok();
    result
}

#[cfg(test)]
mod tests {
    use super::{banner_lines, replace_block};

    #[test]
    fn replaces_or_appends_blocks() {
        let block = "<!-- learn:begin fw (generated) -->\nnew\n<!-- learn:end -->";
        let base = "# Title\n\n<!-- learn:begin fw (generated) -->\nold\n<!-- learn:end -->\ntail\n";
        assert_eq!(replace_block(base, "fw", block), "# Title\n\n<!-- learn:begin fw (generated) -->\nnew\n<!-- learn:end -->\ntail\n");
        assert_eq!(replace_block("# Title\n", "fw", block), format!("# Title\n\n{block}\n"));
    }

    #[test]
    fn reads_the_review_banner_from_the_contract() {
        let text = "prepend `> [!IMPORTANT]` followed by `> Remove this line to confirm.` as the first two lines";
        assert_eq!(banner_lines(text), Some(["> [!IMPORTANT]".to_owned(), "> Remove this line to confirm.".to_owned()]));
    }
}
