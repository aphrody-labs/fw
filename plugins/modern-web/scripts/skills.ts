// Writes skills/<name>/SKILL.md and references/ from the synced sources; every line traces back to a pinned source.
import { cp, mkdir, rm } from "node:fs/promises";
import { join } from "node:path";
import {
  blob,
  files,
  frontmatter,
  pluginRoot,
  type Entry,
  type Pin,
} from "./lib.ts";
import { repos, type Domain, type RepoKey } from "./sources.ts";

interface SpecRow {
  shortname: string;
  title: string;
  url: string;
  date?: string;
  why: string;
  sections: number;
  definitions: number;
  excerpts: number;
  source?: string;
}

interface Inputs {
  pins: Record<RepoKey, Pin>;
  lock: {
    generated: string;
    bunCli: string;
    npm: Record<string, string>;
    forks: Record<string, { ahead: number; behind: number }>;
    releases: Record<string, { latest: string; date: string; count: number }>;
    webref: { crawl: string };
  };
  entriesByDomain: Map<Domain, Entry[]>;
  cli: { revision: string; commands: string[]; help: Record<string, string> };
  guides: {
    id: string;
    description: string;
    category: string;
    path: string;
    features: string[];
  }[];
  specs: SpecRow[];
  forkPages: number;
  upstreamPages: number;
  skillVersion: string;
}

export const skillForDomain: Record<Domain, string> = {
  bun: "bun-reference",
  mwg: "modern-web-guidance",
  webgpu: "webgpu-spec",
  wasm: "webassembly-spec",
  specs: "web-specs",
};

const generated = (inputs: Inputs) =>
  `<!-- Generated by plugins/modern-web/scripts/sync.ts on ${inputs.lock.generated}. Do not edit: run \`bun scripts/sync.ts\` in plugins/modern-web. -->`;

const pinRow = (pin: Pin, role: string) =>
  `| [${pin.repo}](https://github.com/${pin.repo}) | [\`${pin.commit.slice(0, 12)}\`](https://github.com/${pin.repo}/tree/${pin.commit}) | ${pin.date.slice(0, 10)} | ${role} |`;

const pinTable = (inputs: Inputs, keys: RepoKey[]) =>
  [
    "| Source | Commit | Date | Role |",
    "| --- | --- | --- | --- |",
    ...keys.map((key) => pinRow(inputs.pins[key], repos[key].role)),
  ].join("\n");

const query = (domain: Domain) => `## Query the index

Run from this skill's base directory (Bun only; the index is \`data/${domain}.jsonl\`, searched with bun:sqlite FTS5):

\`\`\`sh
bun scripts/query.ts "<2-6 words>"            # ranked hits: title, URL, citation, excerpt
bun scripts/query.ts "<words>" --kind <kind>  # restrict to one kind (see counts below)
bun scripts/query.ts "<words>" --full         # also print the full section text from the pinned source
\`\`\`

Answer from the hits and quote each hit's citation (\`repo@commit path:line\` or \`spec URL (date)\`) next to the claim it supports. If the pinned index looks stale for the question, check the upstream live (\`gh api\`, the spec URL) and say which you used.`;

const kinds = (entries: Entry[]) => {
  const counts = new Map<string, number>();
  for (const entry of entries)
    counts.set(entry.kind, (counts.get(entry.kind) ?? 0) + 1);
  return [...counts]
    .sort()
    .map(([kind, count]) => `\`${kind}\` ${count}`)
    .join(", ");
};

async function writeSkill(
  name: string,
  skill: string,
  references: Record<string, string>,
): Promise<void> {
  const dir = join(pluginRoot, "skills", name);
  await rm(dir, { recursive: true, force: true });
  await mkdir(join(dir, "references"), { recursive: true });
  await Bun.write(join(dir, "SKILL.md"), skill);
  for (const [file, content] of Object.entries(references))
    await Bun.write(join(dir, "references", file), content);
}

const escape = (text: string) =>
  text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function bunSkill(inputs: Inputs): Promise<void> {
  const entries = inputs.entriesByDomain.get("bun") ?? [];
  const pages = entries.filter((entry) => entry.kind.endsWith("-page"));
  const categories = new Map<string, number>();
  for (const page of pages) {
    const path = page.cite.split(" ")[1] ?? "";
    const category = path.split("/").length > 2 ? path.split("/")[1] : "(root)";
    categories.set(category, (categories.get(category) ?? 0) + 1);
  }
  const api = entries.filter((entry) => entry.kind === "api");
  const topLevelApi = api
    .filter((entry) => /^Bun\.[\w$]+(\(\))?$/.test(entry.title))
    .map((entry) => entry.title);
  const releases = Object.entries(inputs.lock.releases).filter(([repo]) =>
    repo.endsWith("/bun"),
  );
  const fork = inputs.lock.forks["aphrody-labs/bun"];
  const skill = `---
name: bun-reference
description: Bun upstream (oven-sh/bun) and the Aphrody fork (aphrody-labs/bun) indexed from source - ${inputs.upstreamPages} docs, guide and blog pages, ${api.length} documented Bun.* and runtime API declarations from packages/bun-types, ${inputs.cli.commands.length} CLI commands from bun --help, release notes. Use for any question about a Bun API, CLI flag, bunfig option, bundler, test runner, package manager or release change; answers carry repo@commit citations.
---

${generated(inputs)}

# Bun reference (upstream + Aphrody fork)

${query("bun")}

Kinds: ${kinds(entries)}.

## Sources (pinned)

${pinTable(inputs, ["bun", "bunFork"])}

- CLI help captured from \`bun ${inputs.cli.revision}\` (\`bun --revision\`); full text in [references/cli.md](references/cli.md).
- Fork vs upstream default branch: ${fork.ahead} commits ahead, ${fork.behind} behind; ${inputs.forkPages} fork docs pages differ from upstream (indexed with the \`(fork ...)\` tag and a GitHub URL).
${releases.map(([repo, release]) => `- Latest ${repo} release: \`${release.latest}\` (${release.date.slice(0, 10)}), ${release.count} releases indexed.`).join("\n")}

## Docs map (pages per directory)

${[...categories]
  .sort((left, right) => right[1] - left[1])
  .map(([category, count]) => `- \`docs/${category}\`: ${count}`)
  .join("\n")}

Full page list with URLs and source lines: [references/docs.md](references/docs.md). API declarations: [references/api.md](references/api.md).

## Top-level \`Bun.*\` APIs documented in bun-types

${topLevelApi.map((title) => `\`${title}\``).join(", ")}
`;
  const docs = [
    "# Bun docs pages",
    "",
    generated(inputs),
    "",
    "| Page | URL | Source |",
    "| --- | --- | --- |",
    ...pages.map(
      (page) => `| ${escape(page.title)} | ${page.url} | \`${page.cite}\` |`,
    ),
  ].join("\n");
  const apiList = [
    "# Bun API declarations (packages/bun-types)",
    "",
    generated(inputs),
    "",
    "| Declaration | Source |",
    "| --- | --- |",
    ...api.map(
      (entry) =>
        `| \`${escape(entry.title)}\` | [${entry.cite}](${entry.url}) |`,
    ),
  ].join("\n");
  const cliDoc = [
    "# Bun CLI help",
    "",
    generated(inputs),
    "",
    `Captured from \`bun ${inputs.cli.revision}\`.`,
    "",
    ...Object.entries(inputs.cli.help).flatMap(([command, text]) => [
      `## bun ${command || ""}`.trim(),
      "",
      "```text",
      Bun.stripANSI(text).trim(),
      "```",
      "",
    ]),
  ].join("\n");
  const releaseList = entries.filter((entry) => entry.kind === "release");
  const releasesDoc = [
    "# Bun releases",
    "",
    generated(inputs),
    "",
    "| Release | Published |",
    "| --- | --- |",
    ...releaseList.map(
      (entry) =>
        `| [${escape(entry.title)}](${entry.url}) | ${entry.cite.match(/\(([^)]+)\)$/)?.[1]?.slice(0, 10) ?? ""} |`,
    ),
  ].join("\n");
  return writeSkill("bun-reference", skill, {
    "docs.md": docs,
    "api.md": apiList,
    "cli.md": cliDoc,
    "releases.md": releasesDoc,
  });
}

// The upstream SKILL.md with the npm runners replaced by bunx and the runner section rewritten for Bun.
async function guidanceSkill(inputs: Inputs): Promise<void> {
  const pin = inputs.pins.mwg;
  const path = "guides/modern-web-guidance/SKILL.md";
  let source = await Bun.file(join(pin.dir, path)).text();
  source = source
    .replaceAll("SKILL_VERSION", inputs.skillVersion)
    .replace(
      /npx -y modern-web-guidance@latest/g,
      "bunx modern-web-guidance@latest",
    )
    .replace(
      /pnpx modern-web-guidance@latest/g,
      "bunx modern-web-guidance@latest",
    )
    .replace(/directly with `npx`/g, "directly with `bunx`")
    .replace(
      /## Using npx \/ pnpx[\s\S]*?(?=\n## )/,
      `## Using bunx

- **Runner & Permissions**: Run the CLI with \`bunx modern-web-guidance@latest\`; never \`npx\`, \`pnpx\` or \`yarn dlx\`. When requesting tool permissions, allowlist \`bunx modern-web-guidance@latest *\` specifically, never bare \`bunx *\`.
- **Sandboxes & Network**: Fetching \`modern-web-guidance\` requires outbound network access to the npm registry; request it before the first execution in sandboxed environments.
- **Offline**: Without network, search the pinned local index instead: \`bun scripts/query.ts "<query>"\` (guides indexed from ${pin.repo}@${pin.commit.slice(0, 12)}).
`,
    );
  const { body } = frontmatter(source);
  const header = source.slice(0, source.length - body.length);
  const entries = inputs.entriesByDomain.get("mwg") ?? [];
  const fork = inputs.lock.forks["aphrody-labs/modern-web-guidance-src"];
  const categories = new Map<string, number>();
  for (const guide of inputs.guides)
    categories.set(guide.category, (categories.get(guide.category) ?? 0) + 1);
  const skill = `${header}
${generated(inputs)}
<!-- Source: ${blob(pin, path)} (skill version ${inputs.skillVersion}; npm modern-web-guidance@${inputs.lock.npm["modern-web-guidance"]}). -->
${body.trimEnd()}

## Local index (modern-web plugin)

${query("mwg").replace("## Query the index\n\n", "")}

Kinds: ${kinds(entries)}. ${inputs.guides.length} guides by category: ${[
    ...categories,
  ]
    .sort()
    .map(([category, count]) => `${category} ${count}`)
    .join(", ")}; full list in [references/guides.md](references/guides.md).

${pinTable(inputs, ["mwg", "mwgFork"])}

The Bun-migrated fork ${repos.mwgFork.repo} is ${fork.ahead} commits ahead and ${fork.behind} behind upstream.
`;
  const list = [
    "# Modern Web Guidance guides",
    "",
    generated(inputs),
    "",
    "| Id (`retrieve`) | Category | Description | web-features | Source |",
    "| --- | --- | --- | --- | --- |",
    ...inputs.guides.map(
      (guide) =>
        `| \`${guide.id}\` | ${guide.category} | ${escape(guide.description)} | ${guide.features.join(", ")} | [${guide.path}](${blob(pin, guide.path)}) |`,
    ),
  ].join("\n");
  await writeSkill("modern-web-guidance", skill, { "guides.md": list });
}

// skills-src/<name> copied with its references; npx invocations become bunx.
async function standaloneSkills(inputs: Inputs): Promise<string[]> {
  const pin = inputs.pins.mwg;
  const names = [
    ...new Set(
      (await files(pin.dir, "skills-src/*/SKILL.md")).map(
        (path) => path.split("/")[1],
      ),
    ),
  ];
  for (const name of names) {
    const target = join(pluginRoot, "skills", name);
    await rm(target, { recursive: true, force: true });
    await cp(join(pin.dir, "skills-src", name), target, { recursive: true });
    for (const path of await files(target, "**/*.md")) {
      const file = join(target, path);
      let text = (await Bun.file(file).text())
        .replace(/\bnpx -y\b/g, "bunx")
        .replace(/\b(npx|pnpx)\b/g, "bunx");
      if (path === "SKILL.md") {
        const { body } = frontmatter(text);
        const header = text.slice(0, text.length - body.length);
        text = `${header}${generated(inputs)}\n<!-- Source: ${blob(pin, `skills-src/${name}`)} -->\n${body}`;
      }
      await Bun.write(file, text);
    }
  }
  return names;
}

function specTable(rows: SpecRow[]): string {
  return [
    "| Spec | Editor's draft | Date | Sections (with source excerpt) | Definitions | Source | Why indexed |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map(
      (row) =>
        `| ${escape(row.title)} (\`${row.shortname}\`) | ${row.url} | ${row.date ?? ""} | ${row.sections} (${row.excerpts}) | ${row.definitions} | ${row.source ? `\`${row.source}\`` : "headings only"} | ${row.why} |`,
    ),
  ].join("\n");
}

function sectionList(entries: Entry[], prefix: string): string {
  return entries
    .filter(
      (entry) =>
        entry.kind === "spec-section" && entry.title.startsWith(prefix),
    )
    .map((entry) => `- [${entry.title.slice(prefix.length)}](${entry.url})`)
    .join("\n");
}

async function webgpuSkill(inputs: Inputs): Promise<void> {
  const entries = inputs.entriesByDomain.get("webgpu") ?? [];
  const rows = inputs.specs.filter(
    (row) =>
      row.source?.startsWith("gpuweb/gpuweb") ||
      row.url.includes("gpuweb.github.io"),
  );
  const top = (label: string) =>
    entries
      .filter(
        (entry) =>
          entry.kind === "spec-section" &&
          entry.title.startsWith(`${label} § `) &&
          /§ \d+ /.test(entry.title),
      )
      .map(
        (entry) => `[${entry.title.replace(`${label} § `, "")}](${entry.url})`,
      )
      .join(" · ");
  const wgpu = inputs.lock.releases["gfx-rs/wgpu"];
  const skill = `---
name: webgpu-spec
description: WebGPU and WGSL specifications (gpuweb/gpuweb Bikeshed sources + w3c/webref sections and IDL/WGSL definitions) and wgpu/Naga (gfx-rs/wgpu changelog, docs, documented public API) indexed with spec URL#anchor and repo@commit citations. Use for WebGPU API semantics (GPUCanvasContext, configure, getCurrentTexture, canvas sizing, limits, features, pipelines, bind groups, buffers, textures), WGSL grammar, built-ins and types, and wgpu/Naga version changes.
---

${generated(inputs)}

# WebGPU, WGSL, wgpu and Naga

${query("webgpu")}

Kinds: ${kinds(entries)}.

## Sources (pinned)

${pinTable(inputs, ["gpuweb", "wgpu", "webref"])}

${wgpu ? `Latest wgpu release: \`${wgpu.latest}\` (${wgpu.date.slice(0, 10)}).` : ""}

${specTable(rows)}

## WebGPU chapters

${top("WebGPU")}

## WGSL chapters

${top("WGSL")}

All sections: [references/webgpu.md](references/webgpu.md), [references/wgsl.md](references/wgsl.md).
`;
  await writeSkill("webgpu-spec", skill, {
    "webgpu.md": `# WebGPU sections\n\n${generated(inputs)}\n\n${sectionList(entries, "WebGPU § ")}\n`,
    "wgsl.md": `# WGSL sections\n\n${generated(inputs)}\n\n${sectionList(entries, "WGSL § ")}\n`,
  });
}

async function wasmSkill(inputs: Inputs): Promise<void> {
  const entries = inputs.entriesByDomain.get("wasm") ?? [];
  const rows = inputs.specs.filter(
    (row) =>
      /webassembly/i.test(row.url) || row.source?.startsWith("WebAssembly/"),
  );
  const bindgen = inputs.lock.releases["wasm-bindgen/wasm-bindgen"];
  const skill = `---
name: webassembly-spec
description: WebAssembly specifications (WebAssembly/spec core RST, JS API and Web API Bikeshed sources, every WebAssembly proposal spec in w3c/webref), WASI proposals and WIT interfaces (WebAssembly/WASI) and the wasm-bindgen guide and changelog, indexed with spec URL#anchor or repo@commit citations. Use for Wasm instruction and validation semantics, module structure, JS API (WebAssembly.instantiateStreaming, Memory, Table, Global, Tag), WASI interfaces and wasm-bindgen attributes.
---

${generated(inputs)}

# WebAssembly, WASI and wasm-bindgen

${query("wasm")}

Kinds: ${kinds(entries)}.

## Sources (pinned)

${pinTable(inputs, ["wasmSpec", "wasi", "wasmBindgen", "webref"])}

${bindgen ? `Latest wasm-bindgen release: \`${bindgen.latest}\` (${bindgen.date.slice(0, 10)}).` : ""}

${specTable(rows)}

WASI interfaces: [references/wasi.md](references/wasi.md).
`;
  const wit = entries
    .filter((entry) => entry.kind === "wit")
    .map((entry) => `- [${entry.title}](${entry.url})`)
    .join("\n");
  await writeSkill("webassembly-spec", skill, {
    "wasi.md": `# WASI WIT items\n\n${generated(inputs)}\n\n${wit}\n`,
  });
}

async function specsSkill(inputs: Inputs): Promise<void> {
  const entries = inputs.entriesByDomain.get("specs") ?? [];
  const rows = inputs.specs.filter(
    (row) => !/webassembly|gpuweb/i.test(`${row.url} ${row.source ?? ""}`),
  );
  const whatwg = rows.filter((row) => row.why === "WHATWG standard");
  const skill = `---
name: web-specs
description: W3C and WHATWG specifications relevant to Bun, Modern Web Guidance, WebGPU and WebAssembly (${rows.length} specs - every WHATWG standard plus the W3C specs that Modern Web Guidance web-features or Bun docs link to), indexed by spec URL#section with webref definitions (IDL interfaces, methods, CSS properties, elements) and source excerpts. Use to cite the normative section for fetch, streams, URL, encoding, HTML, DOM, WebIDL, CSS and other web platform behaviour.
---

${generated(inputs)}

# W3C and WHATWG specs

${query("specs")}

Kinds: ${kinds(entries)}.

## Sources (pinned)

${pinTable(inputs, ["webref"])}

Webref crawl: ${inputs.lock.webref.crawl}. Selection is derived on every sync: WHATWG standards (${whatwg.length}), and W3C specs whose URL appears in the web-features \`spec\` field of a Modern Web Guidance guide or in a Bun docs page.

Spec list with dates, counts and sources: [references/specs.md](references/specs.md).
`;
  await writeSkill("web-specs", skill, {
    "specs.md": `# Indexed specs\n\n${generated(inputs)}\n\n${specTable(rows)}\n`,
  });
}

export async function writeSkills(inputs: Inputs): Promise<void> {
  await bunSkill(inputs);
  await guidanceSkill(inputs);
  await standaloneSkills(inputs);
  await webgpuSkill(inputs);
  await wasmSkill(inputs);
  await specsSkill(inputs);
}
