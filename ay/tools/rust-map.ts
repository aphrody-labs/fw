#!/usr/bin/env bun
// .private/linux/rust-map.toml: the userland's Rust replacements (os/linux/linux.toml [[rust_map]]) with the Arch package state read live. Generated; edit os/linux/linux.toml.
//   bun tools/rust-map.ts
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");

export type Entry = { component: string; replaces: string; rust: string; upstream: string; arch_pkg?: string; status?: string };
export type Row = Entry & { status: string; repo: string; version: string };
export type Lookup = (pkg: string) => Promise<{ repo: string; version: string } | undefined>;

export const archLookup: Lookup = async (pkg) => {
  const res = await fetch(`https://archlinux.org/packages/search/json/?name=${encodeURIComponent(pkg)}`, { headers: { "user-agent": "ay-linux-rust-map" } });
  if (!res.ok) throw new Error(`archlinux.org: HTTP ${res.status}`);
  const hit = ((await res.json()) as { results: { repo: string; pkgname: string; pkgver: string }[] }).results.find((r) => r.pkgname === pkg);
  return hit ? { repo: hit.repo, version: hit.pkgver } : undefined;
};

export async function resolve_(entries: Entry[], lookup: Lookup): Promise<Row[]> {
  const rows: Row[] = [];
  for (const e of entries) {
    const hit = e.arch_pkg ? await lookup(e.arch_pkg) : undefined;
    const status = e.status ?? (hit ? "ships" : e.arch_pkg ? "aur" : "none");
    rows.push({ ...e, status, repo: hit?.repo ?? "", version: hit?.version ?? "" });
  }
  return rows;
}

export function toToml(rows: Row[], generated: string): string {
  const q = (s: string) => JSON.stringify(s);
  const out = [`# Generated by tools/rust-map.ts on ${generated}; edit os/linux/linux.toml [[rust_map]], not this file.`, `rows = ${rows.length}`, `shipping = ${rows.filter((r) => r.status === "ships").length}`, ""];
  for (const r of rows) out.push("[[row]]", `component = ${q(r.component)}`, `replaces = ${q(r.replaces)}`, `rust = ${q(r.rust)}`, `upstream = ${q(r.upstream)}`, `status = ${q(r.status)}`, `repo = ${q(r.repo)}`, `version = ${q(r.version)}`, "");
  return out.join("\n");
}

if (import.meta.main) {
  const entries = (Bun.TOML.parse(await Bun.file(join(root, "os/linux/linux.toml")).text()) as { rust_map: Entry[] }).rust_map;
  const rows = await resolve_(entries, archLookup);
  await Bun.write(join(root, ".private/linux/rust-map.toml"), toToml(rows, new Date().toISOString().slice(0, 10)));
  const c = (s: string) => rows.filter((r) => r.status === s).length;
  console.log(`${rows.length} components: ${c("ships")} ship in Arch, ${c("aur")} AUR only, ${c("experimental")} experimental, ${c("none")} none`);
}
