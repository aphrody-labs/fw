#!/usr/bin/env bun
// The feature matrix: docs/features.toml is the scope of every product.
//   bun tools/features.ts          write docs/features.md from the matrix
//   bun tools/features.ts --check  fail when docs/features.md is stale, a row is malformed,
//                                  or a `done` row has no proof (or a local proof path that doesn't exist)
// Proof forms: an https URL; `path` or `path::test name` in this repository; `<repo>:path[::test name]` in the checkout of
// another [repos] key of ay.toml (verified when that checkout is present, accepted otherwise).
import { checkoutOf, readAy } from "./local.ts";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export type Feature = {
  product: string;
  id: string;
  title: string;
  reference: string;
  layer: "ui" | "backend" | "protocol" | "os";
  status: "todo" | "doing" | "done";
  /** Key of [repos] in ay.toml that builds this row; defaults to the owner of the product. */
  owner?: string;
  proof?: string;
  proof_kind?: "test" | "screenshot" | "log" | "hardware";
};

const root = resolve(import.meta.dir, "..");
const LAYERS = new Set(["ui", "backend", "protocol", "os"]);
const STATUSES = new Set(["todo", "doing", "done"]);

export function load(text: string): Feature[] {
  const parsed = Bun.TOML.parse(text) as { feature?: Feature[] };
  return parsed.feature ?? [];
}

/** The file part of a proof: the test id after `::` is dropped. */
export const proofPath = (proof: string): string => proof.split("::")[0]!;

/** Splits `<repo>:path` (a [repos] key of ay.toml) from a plain repository path; Windows drives and URLs are not repo keys. */
export function splitRepoProof(path: string, repos: Set<string>): { repo?: string; path: string } {
  const m = /^([A-Za-z][\w-]+):(?![\\/])(.+)$/.exec(path);
  return m && repos.has(m[1]!) ? { repo: m[1], path: m[2]! } : { path };
}

/** Owners: the default owner of each product and the keys of [repos] (both from ay.toml). */
export type Owners = { byProduct: Record<string, string>; repos: Set<string> };

export function ownerOf(f: Feature, owners: Owners): string | undefined {
  return f.owner ?? owners.byProduct[f.product];
}

/** Problems in the matrix; `products` are the keys of [products] in ay.toml plus "platform". */
export function problems(features: Feature[], products: Set<string>, exists: (path: string) => boolean, owners?: Owners): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const f of features) {
    const key = `${f.product}/${f.id}`;
    if (seen.has(key)) out.push(`${key}: duplicate id`);
    seen.add(key);
    if (!products.has(f.product)) out.push(`${key}: unknown product`);
    if (!LAYERS.has(f.layer)) out.push(`${key}: unknown layer ${f.layer}`);
    if (!STATUSES.has(f.status)) out.push(`${key}: unknown status ${f.status}`);
    if (!/^https:\/\//.test(f.reference)) out.push(`${key}: reference is not an https URL`);
    if (owners) {
      const o = ownerOf(f, owners);
      if (!o) out.push(`${key}: no owner (set owner on the row or on the product)`);
      else if (!owners.repos.has(o)) out.push(`${key}: owner ${o} is not a key of [repos]`);
    }
    if (f.status === "done") {
      if (!f.proof) out.push(`${key}: done without proof`);
      else if (!/^https:\/\//.test(f.proof) && !exists(proofPath(f.proof))) out.push(`${key}: proof ${f.proof} does not exist`);
    }
  }
  return out;
}

export function render(features: Feature[], owners?: Owners): string {
  const lines = [
    "# Feature matrix",
    "",
    "Generated by `bun tools/features.ts` from `docs/features.toml`. Do not edit.",
    "",
  ];
  if (owners) {
    const by = new Map<string, { rows: number; done: number }>();
    for (const f of features) {
      const o = ownerOf(f, owners) ?? "unowned";
      const s = by.get(o) ?? { rows: 0, done: 0 };
      s.rows++;
      if (f.status === "done") s.done++;
      by.set(o, s);
    }
    lines.push("## Rows by owner", "", "| Owner | Rows | Done |", "|---|---|---|");
    for (const [o, s] of [...by].sort((a, b) => b[1].rows - a[1].rows)) lines.push(`| ${o} | ${s.rows} | ${s.done} |`);
    lines.push("");
  }
  const products = [...new Set(features.map(f => f.product))];
  for (const p of products) {
    const rows = features.filter(f => f.product === p);
    const done = rows.filter(f => f.status === "done").length;
    lines.push(`## ${p} (${done}/${rows.length} done)`, "", owners ? "| Feature | Owner | Layer | Status | Proof | Reference |" : "| Feature | Layer | Status | Proof | Reference |", owners ? "|---|---|---|---|---|---|" : "|---|---|---|---|---|");
    for (const f of rows) {
      const proof = f.proof ?? (f.proof_kind === "hardware" ? "needs hardware" : "");
      const o = owners ? ` ${ownerOf(f, owners) ?? ""} |` : "";
      lines.push(`| ${f.title.replaceAll("|", "\\|")} |${o} ${f.layer} | ${f.status} | ${proof} | <${f.reference}> |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (import.meta.main) {
  const features = load(readFileSync(join(root, "docs/features.toml"), "utf8"));
  const ay = readAy(root) as unknown as { products?: Record<string, { owner?: string }>; matrix?: { platform_owner?: string }; repos?: Record<string, unknown> };
  const products = new Set([...Object.keys(ay.products ?? {}), "platform"]);
  const owners: Owners = {
    byProduct: {
      ...(ay.matrix?.platform_owner ? { platform: ay.matrix.platform_owner } : {}),
      ...Object.fromEntries(Object.entries(ay.products ?? {}).flatMap(([k, v]) => (v.owner ? [[k, v.owner]] : []))),
    },
    repos: new Set(Object.keys(ay.repos ?? {})),
  };
  const cfg = readAy(root);
  const proofExists = (p: string): boolean => {
    const { repo, path } = splitRepoProof(p, owners.repos);
    if (!repo) return existsSync(join(root, path));
    const base = checkoutOf(repo, cfg, root);
    return !existsSync(base) || existsSync(join(base, path));
  };
  const issues = problems(features, products, proofExists, owners);
  const md = render(features, owners);
  const target = join(root, "docs/features.md");
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== md) issues.push("docs/features.md is stale (run bun tools/features.ts)");
    for (const i of issues) console.error(`features: ${i}`);
    process.exit(issues.length ? 1 : 0);
  }
  if (issues.length) {
    for (const i of issues) console.error(`features: ${i}`);
    process.exit(1);
  }
  writeFileSync(target, md);
  console.log(`docs/features.md: ${features.length} features`);
}
