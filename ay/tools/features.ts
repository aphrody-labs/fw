#!/usr/bin/env bun
// The feature matrix: docs/features.toml is the scope of every product.
//   bun tools/features.ts          write docs/features.md from the matrix
//   bun tools/features.ts --check  fail when docs/features.md is stale, a row is malformed,
//                                  or a `done` row has no proof (or a repo-path proof that doesn't exist)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export type Feature = {
  product: string;
  id: string;
  title: string;
  reference: string;
  layer: "ui" | "backend" | "protocol" | "os";
  status: "todo" | "doing" | "done";
  proof?: string;
  proof_kind?: "test" | "screenshot" | "log" | "hardware";
};

const root = resolve(import.meta.dir, "..");
const LAYERS = new Set(["ui", "backend", "protocol", "os"]);
const STATUSES = new Set(["todo", "doing", "done"]);

export function load(text: string): Feature[] {
  const parsed = Bun.TOML.parse(text) as { feature?: Feature[] };
  return parsed.feature ?? [];
}

/** Problems in the matrix; `products` are the keys of [products] in ay.toml plus "platform". */
export function problems(features: Feature[], products: Set<string>, exists: (path: string) => boolean): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const f of features) {
    const key = `${f.product}/${f.id}`;
    if (seen.has(key)) out.push(`${key}: duplicate id`);
    seen.add(key);
    if (!products.has(f.product)) out.push(`${key}: unknown product`);
    if (!LAYERS.has(f.layer)) out.push(`${key}: unknown layer ${f.layer}`);
    if (!STATUSES.has(f.status)) out.push(`${key}: unknown status ${f.status}`);
    if (!/^https:\/\//.test(f.reference)) out.push(`${key}: reference is not an https URL`);
    if (f.status === "done") {
      if (!f.proof) out.push(`${key}: done without proof`);
      else if (!/^https:\/\//.test(f.proof) && !f.proof.includes("::") && !exists(f.proof))
        out.push(`${key}: proof ${f.proof} does not exist`);
    }
  }
  return out;
}

export function render(features: Feature[]): string {
  const lines = [
    "# Feature matrix",
    "",
    "Generated by `bun tools/features.ts` from `docs/features.toml`. Do not edit.",
    "",
  ];
  const products = [...new Set(features.map(f => f.product))];
  for (const p of products) {
    const rows = features.filter(f => f.product === p);
    const done = rows.filter(f => f.status === "done").length;
    lines.push(`## ${p} (${done}/${rows.length} done)`, "", "| Feature | Layer | Status | Proof | Reference |", "|---|---|---|---|---|");
    for (const f of rows) {
      const proof = f.proof ?? (f.proof_kind === "hardware" ? "needs hardware" : "");
      lines.push(`| ${f.title.replaceAll("|", "\\|")} | ${f.layer} | ${f.status} | ${proof} | <${f.reference}> |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (import.meta.main) {
  const features = load(readFileSync(join(root, "docs/features.toml"), "utf8"));
  const ay = Bun.TOML.parse(readFileSync(join(root, "ay.toml"), "utf8")) as { products?: Record<string, unknown> };
  const products = new Set([...Object.keys(ay.products ?? {}), "platform"]);
  const issues = problems(features, products, p => existsSync(join(root, p)));
  const md = render(features);
  const target = join(root, "docs/features.md");
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== md) issues.push("docs/features.md is stale (run bun tools/features.ts)");
    for (const i of issues) console.error(`features: ${i}`);
    process.exit(issues.length ? 1 : 0);
  }
  if (issues.length) {
    for (const i of issues) console.error(`features: ${i}`);
    process.exit(1);
  }
  writeFileSync(target, md);
  console.log(`docs/features.md: ${features.length} features`);
}
