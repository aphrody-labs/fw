#!/usr/bin/env bun
// Renders the Material 3 colour tokens (brand/tokens/m3-tokens.json) as a Jetpack Compose Material 3 theme:
// `lightColorScheme(...)` and `darkColorScheme(...)` with every role of androidx.compose.material3.ColorScheme
// (1.5 stable: the surface containers and the fixed roles included), so Android and Kotlin targets use the same
// colours as CSS, Tailwind and Figma. The Kotlin package is the reversed root domain of ay.toml [domains].
//   bun tools/tokens-compose.ts [--check]   (--check exits 1 when the committed file is not what the tokens give)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { readAy, repoRoot } from "./local.ts";

/** Parameters of `lightColorScheme` / `darkColorScheme` in Compose Material 3 1.5, in declaration order. */
export const COMPOSE_ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceTint",
  "inverseSurface", "inverseOnSurface", "error", "onError", "errorContainer", "onErrorContainer",
  "outline", "outlineVariant", "scrim",
  "surfaceBright", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "surfaceContainerLow", "surfaceContainerLowest", "surfaceDim",
  "primaryFixed", "primaryFixedDim", "onPrimaryFixed", "onPrimaryFixedVariant",
  "secondaryFixed", "secondaryFixedDim", "onSecondaryFixed", "onSecondaryFixedVariant",
  "tertiaryFixed", "tertiaryFixedDim", "onTertiaryFixed", "onTertiaryFixedVariant",
] as const;

export type Scheme = Record<string, string>;
export type Tokens = { seed: string; variant: string; light: Scheme; dark: Scheme };

/** `#rrggbb` -> `Color(0xFFRRGGBB)`. */
export function composeColor(hex: string): string {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`not a #rrggbb colour: ${hex}`);
  return `Color(0xFF${(m[1] as string).toUpperCase()})`;
}

/** `aphrody.com` -> `com.aphrody`. */
export function kotlinPackage(rootDomain: string): string {
  return rootDomain.split(".").reverse().map((p) => p.replace(/[^a-z0-9_]/gi, "_").toLowerCase()).join(".");
}

function scheme(fn: string, s: Scheme): string {
  const missing = COMPOSE_ROLES.filter((r) => !s[r]);
  if (missing.length) throw new Error(`${fn}: tokens lack ${missing.join(", ")}`);
  return [`val ${fn === "lightColorScheme" ? "AphrodyLightColors" : "AphrodyDarkColors"}: ColorScheme = ${fn}(`, ...COMPOSE_ROLES.map((r) => `    ${r} = ${composeColor(s[r] as string)},`), ")"].join("\n");
}

export function render(tokens: Tokens, pkg: string): string {
  return [
    "// Generated by tools/tokens-compose.ts from brand/tokens/m3-tokens.json; edit the tokens, not this file.",
    `// Seed ${tokens.seed}, variant ${tokens.variant}.`,
    `package ${pkg}.theme`,
    "",
    "import androidx.compose.material3.ColorScheme",
    "import androidx.compose.material3.darkColorScheme",
    "import androidx.compose.material3.lightColorScheme",
    "import androidx.compose.ui.graphics.Color",
    "",
    scheme("lightColorScheme", tokens.light),
    "",
    scheme("darkColorScheme", tokens.dark),
    "",
  ].join("\n");
}

export const OUT = join(repoRoot, "brand", "tokens", "compose", "AphrodyColorScheme.kt");

if (import.meta.main) {
  const tokens = JSON.parse(readFileSync(join(repoRoot, "brand", "tokens", "m3-tokens.json"), "utf8")) as Tokens;
  const root = (readAy() as { domains?: { root?: string } }).domains?.root;
  if (!root) throw new Error("ay.toml [domains].root is not set");
  const body = render(tokens, kotlinPackage(root));
  if (Bun.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== body) {
      console.error(`${OUT} is stale: run bun tools/tokens-compose.ts`);
      process.exit(1);
    }
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, body);
  }
  console.log(`${COMPOSE_ROLES.length} roles x 2 schemes -> ${OUT}`);
}
