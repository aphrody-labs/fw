#!/usr/bin/env bun
// Renders docs/plan.md: the work ledger (docs/plan/work.toml) joined with the live claim results, the ADR index, the
// feature matrix counts and the org inventory headline. Nothing in the output is typed by hand twice.
//   bun tools/plan.ts          write docs/plan.md
//   bun tools/plan.ts --check  fail when docs/plan.md is not what the sources generate
import { join, resolve } from "node:path";
import type { Result } from "./claims.ts";

const root = resolve(import.meta.dir, "..");

export type Item = { id: string; title: string; status: "done" | "running" | "open" | "blocked"; owner?: string; claims?: string[]; next?: string };
type Toml = Record<string, any>;

export const health = (item: Item, results: Map<string, Result>): "verified" | "attention" | "unchecked" => {
  const rs = (item.claims ?? []).map((id) => results.get(id));
  if (!rs.length) return "unchecked";
  if (rs.some((r) => r?.status === "failed" || r === undefined)) return "attention";
  return rs.every((r) => r?.status === "proved") ? "verified" : "attention";
};

export function render(work: Item[], results: Result[], adr: string, features: Toml[], inventory: Toml | undefined): string {
  const byId = new Map(results.map((r) => [r.id, r]));
  const count = (s: Item["status"]) => work.filter((i) => i.status === s).length;
  const out = ["# Plan", "", "<!-- Generated by tools/plan.ts from docs/plan/work.toml and docs/research/claims-status.json; do not edit. -->", ""];
  const checked = results.map((r) => r.checked).sort().at(-1) ?? "never";
  out.push(`Work: ${count("running")} running, ${count("open")} open, ${count("blocked")} blocked on the owner or a credential, ${count("done")} done. Claims: ${results.filter((r) => r.status === "proved").length} of ${results.length} proved on ${checked}.`, "");
  out.push("## Work", "", "| Item | Status | Owner | Evidence | Next |", "|---|---|---|---|---|");
  const order = ["blocked", "running", "open", "done"];
  for (const i of [...work].sort((a, b) => order.indexOf(a.status) - order.indexOf(b.status))) out.push(`| ${i.title} | ${i.status} | ${i.owner ?? ""} | ${health(i, byId)} | ${i.next ?? ""} |`);
  const bad = results.filter((r) => r.status !== "proved");
  out.push("", "## Claims that do not hold now", "");
  out.push(...(bad.length ? ["| Claim | Status | Observed |", "|---|---|---|", ...bad.map((r) => `| ${r.text} (\`${r.id}\`) | ${r.status} | ${r.observed.replaceAll("|", "/")} |`)] : ["None."]));
  const rows = adr.split("\n").filter((l) => /^\| \[\d{4}\]/.test(l)).map((l) => l.split("|").map((c) => c.trim()));
  out.push("", "## Decisions (ADR)", "", "| ADR | Decision | Status |", "|---|---|---|", ...rows.map((c) => `| ${c[1]} | ${c[2]} | ${c[3]} |`));
  const tally: Record<string, Record<string, number>> = {};
  for (const f of features) ((tally[f.product] ??= {})[f.status] = (tally[f.product]![f.status] ?? 0) + 1);
  out.push("", "## Feature matrix", "", "| Product | Done | Other |", "|---|---:|---:|");
  for (const [p, t] of Object.entries(tally)) out.push(`| ${p} | ${t.done ?? 0} | ${Object.entries(t).filter(([s]) => s !== "done").reduce((n, [, v]) => n + v, 0)} |`);
  if (inventory) {
    const gh = inventory.github as Record<string, { repos?: number; forks?: number }>;
    const cf = inventory.cloudflare as Toml;
    out.push("", "## Estate", "", ...Object.entries(gh).map(([o, v]) => `- ${o}: ${v.repos} repositories, ${v.forks} forks`), `- Cloudflare: ${cf.zones?.length} zones, ${cf.workers?.length} Workers, ${cf.queues?.length} queues, ${cf.r2?.length} R2 buckets, ${cf.tunnels?.length} tunnels`, `- Registries: ${inventory.registries?.npm?.packages} npm packages, ${inventory.registries?.crates?.published} crates`);
  }
  out.push("");
  return out.join("\n");
}

const read = async (p: string) => Bun.file(join(root, p)).text();

export async function build(): Promise<string> {
  const work = (Bun.TOML.parse(await read("docs/plan/work.toml")) as { item: Item[] }).item;
  const results = JSON.parse(await read("docs/research/claims-status.json")) as Result[];
  const features = (Bun.TOML.parse(await read("docs/features.toml")) as { feature: Toml[] }).feature;
  const inv = (await Bun.file(join(root, "docs/research/org-inventory.toml")).exists()) ? (Bun.TOML.parse(await read("docs/research/org-inventory.toml")) as Toml) : undefined;
  return render(work, results, await read("docs/adr/README.md"), features, inv);
}

if (import.meta.main) {
  const text = await build();
  const path = join(root, "docs/plan.md");
  if (process.argv.includes("--check")) {
    if ((await Bun.file(path).text()) !== text) (console.error("docs/plan.md is stale: run bun tools/plan.ts"), process.exit(1));
  } else await Bun.write(path, text);
  console.log("plan ok");
}
