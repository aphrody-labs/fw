// Reads os/linux/linux.toml, lists each source org live through `gh api`, and writes .private/linux/sources.toml.
import { $ } from "bun";

type Source = { org: string; take: "all" | "rust"; min_stars?: number; dir: string };
type Repo = { name: string; full_name: string; language: string | null; stargazers_count: number; archived: boolean; fork: boolean; pushed_at: string };
export type Entry = { slug: string; dir: string; language: string; stars: number; pushed: string };

export function select(src: Source, repos: Repo[]): Entry[] {
  return repos
    .filter(r => !r.archived && !r.fork)
    .filter(r => src.take === "all" || (r.language === "Rust" && r.stargazers_count >= (src.min_stars ?? 0)))
    .sort((a, b) => b.stargazers_count - a.stargazers_count)
    .map(r => ({ slug: r.full_name, dir: `${src.dir}/${r.name}`, language: r.language ?? "", stars: r.stargazers_count, pushed: r.pushed_at.slice(0, 10) }));
}

// Picks land under their group; a generic name ("kernel") keeps its owner so two picks never share a directory.
export function pickDir(group: string, slug: string, taken: Set<string> = new Set()): string {
  const [owner, name] = slug.split("/") as [string, string];
  const plain = `${group}/${name}`;
  return taken.has(plain.toLowerCase()) || name.toLowerCase() === group.toLowerCase() || name === "kernel" ? `${group}/${owner}-${name}` : plain;
}

export function toToml(entries: Entry[]): string {
  const q = (s: string) => JSON.stringify(s);
  return "# Generated by tools/linux-sources.ts from os/linux/linux.toml; do not edit.\n" +
    entries.map(e => `\n[[source]]\nslug = ${q(e.slug)}\ndir = ${q(e.dir)}\nlanguage = ${q(e.language)}\nstars = ${e.stars}\npushed = ${q(e.pushed)}\n`).join("");
}

async function orgRepos(org: string): Promise<Repo[]> {
  const out = await $`gh api --paginate ${`orgs/${org}/repos?per_page=100&type=public`} --jq ${".[]"}`.text();
  return out.trim().split("\n").filter(Boolean).map(l => JSON.parse(l) as Repo);
}

async function repo(slug: string): Promise<Repo | null> {
  const r = await $`gh api ${`repos/${slug}`}`.quiet().nothrow();
  return r.exitCode === 0 ? (JSON.parse(r.stdout.toString()) as Repo) : null;
}

if (import.meta.main) {
  const cfg = Bun.TOML.parse(await Bun.file(new URL("../os/linux/linux.toml", import.meta.url)).text()) as { sources: Record<string, Source>; picks: Record<string, string[]> };
  const entries: Entry[] = [];
  const taken = new Set<string>();
  for (const src of Object.values(cfg.sources)) entries.push(...select(src, await orgRepos(src.org)));
  for (const [group, slugs] of Object.entries(cfg.picks))
    for (const slug of slugs) {
      const r = await repo(slug);
      if (!r) { console.error(`missing: ${slug}`); continue; }
      taken.add(pickDir(group, r.full_name, taken).toLowerCase());
      entries.push({ slug: r.full_name, dir: pickDir(group, r.full_name, taken), language: r.language ?? "", stars: r.stargazers_count, pushed: r.pushed_at.slice(0, 10) });
    }
  const seen = new Set<string>();
  const unique = entries.filter(e => !seen.has(e.slug.toLowerCase()) && seen.add(e.slug.toLowerCase()));
  await Bun.write(new URL("../.private/linux/sources.toml", import.meta.url), toToml(unique));
  console.log(`${unique.length} sources -> .private/linux/sources.toml`);
}
