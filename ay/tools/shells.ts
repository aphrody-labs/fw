#!/usr/bin/env bun
/**
 * Installs the shell and terminal configuration of config/ on this machine.
 *
 *   bun tools/shells.ts           # generate and install, idempotent
 *   bun tools/shells.ts --check   # report every difference, exit 1 when there is one
 *   bun tools/shells.ts --gen     # only (re)generate the env files and the completions
 *
 * What it writes, and where:
 *   - env.sh and env.ps1, generated from config/env.toml, into the shell cache directory (AY_SHELL_CACHE);
 *   - the stubs ~/.bashrc, ~/.bash_profile and ~/.niubashrc, which source config/bash from this checkout;
 *   - the copies listed in config/links.toml (PowerShell profiles, starship, atuin, yazi, ...), for the tools that are
 *     on PATH; a link whose tool is absent is dropped, never written;
 *   - the git and bun completions (bash) and the `ay` completions, from the tools that are installed;
 *   - the variables of [persist.windows] in HKCU\Environment, and the include of the delta configuration in ~/.gitconfig.
 *
 * SRC_ROOT, the workspace root, is the parent of this checkout: it is derived here and never written to a tracked file.
 * Output lines start with `ok`, `set` (written), `DIFF` (differs, --check), `rm`, or `info`.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, posix, resolve, win32 } from "node:path";

export type Plat = "windows" | "linux" | "darwin";

/** Everything the installer reads from the machine, injectable for tests. */
export interface Host {
  plat: Plat;
  home: string;
  appdata: string;
  localappdata: string;
  programfiles: string;
  /** The aysh checkout. */
  root: string;
  /** The absolute path of a binary on PATH, or undefined. */
  which: (name: string) => string | undefined;
  /** Stdout of a command, or null when it fails. */
  run: (argv: string[]) => string | null;
}

export function currentHost(): Host {
  const win = process.platform === "win32";
  return {
    plat: win ? "windows" : process.platform === "darwin" ? "darwin" : "linux",
    home: (win ? process.env.USERPROFILE : process.env.HOME) ?? "",
    appdata: process.env.APPDATA ?? "",
    localappdata: process.env.LOCALAPPDATA ?? "",
    programfiles: process.env.ProgramFiles ?? "",
    root: resolve(import.meta.dir, ".."),
    which: (name) => Bun.which(name) ?? undefined,
    run: (argv) => {
      try {
        const r = Bun.spawnSync(argv, { stdout: "pipe", stderr: "pipe", timeout: 5000 });
        return r.exitCode === 0 ? r.stdout.toString() : null;
      } catch {
        return null;
      }
    },
  };
}

const CONFIG = (h: Host) => join(h.root, "config");

/** The workspace root: the directory that holds this checkout next to the other repositories. */
export const srcRoot = (h: Host) => dirname(h.root);

const slashes = (p: string) => p.replaceAll("\\", "/");
const HEADER = "generated by tools/shells.ts from config/env.toml, do not edit";

// --- env.toml --------------------------------------------------------------------------------------------------------

interface VarDef {
  /** Keep a value already set by the OS environment (a toolchain on another drive); the toml value is the fallback. */
  keep?: boolean;
  all?: string;
  windows?: string;
  linux?: string;
  darwin?: string;
}

export interface EnvToml {
  var: Record<string, VarDef>;
  path: Partial<Record<Plat | "front", string[]>>;
  persist?: { windows?: Record<string, string> };
}

type Part = { lit: string } | { home: true } | { ref: string };

export const loadEnv = (h: Host): EnvToml => Bun.TOML.parse(readFileSync(join(CONFIG(h), "env.toml"), "utf8")) as EnvToml;

/** Splits a value into literals, `{home}` and `{NAME}` references; `{programfiles}` is resolved now. */
export function parts(value: string, h: Host): Part[] {
  const out: Part[] = [];
  const v = value.replaceAll("{programfiles}", h.programfiles);
  for (const [i, s] of v.split(/\{([A-Za-z_][A-Za-z0-9_]*)\}/).entries()) {
    if (i % 2 === 0) {
      if (s) out.push({ lit: s });
    } else out.push(s === "home" ? { home: true } : { ref: s });
  }
  return out;
}

/** The variables of one platform: SRC_ROOT first (derived), then env.toml in file order. darwin follows linux. */
export function vars(e: EnvToml, plat: Plat, h: Host): { name: string; value: Part[]; keep?: boolean }[] {
  const root = srcRoot(h);
  const derived = [{ name: "SRC_ROOT", value: [{ lit: plat === "windows" ? root.replaceAll("/", "\\") : root }] as Part[] }];
  const listed = Object.entries(e.var).flatMap(([name, d]) => {
    const v = d[plat] ?? (plat === "darwin" ? d.linux : undefined) ?? d.all;
    return v === undefined ? [] : [{ name, value: parts(v, h), keep: d.keep }];
  });
  return [...derived, ...listed];
}

const dirs = (e: EnvToml, plat: Plat) => e.path[plat] ?? (plat === "darwin" ? e.path.linux : undefined) ?? [];

// --- emitters --------------------------------------------------------------------------------------------------------

const sq = (s: string) => `'${s.replaceAll("'", `'\\''`)}'`;

export function emitSh(e: EnvToml, h: Host): string {
  const val = (ps: Part[]) =>
    ps.map((x) => ("lit" in x ? sq(x.lit) : "home" in x ? `"$_ay_h"` : `"\${${x.ref}}"`)).join("");
  const branch = (active: boolean, plat: Plat) => {
    if (!active) return "  :";
    const l: string[] = [];
    for (const v of vars(e, plat, h))
      l.push(v.keep ? `  [ -n "\${${v.name}-}" ] || export ${v.name}=${val(v.value)}` : `  export ${v.name}=${val(v.value)}`);
    const front = new Set(e.path.front ?? []);
    for (const d of [...dirs(e, plat)].reverse()) l.push(`  _ay_pp ${val(parts(d, h))}${front.has(d) ? " m" : ""}`);
    return l.join("\n");
  };
  const win = h.plat === "windows";
  return `# ${HEADER}
# Bash family (bash, niubash, aysh, Git Bash, brush). Idempotent, builtins only, safe when non-interactive.
# Windows PATH: ';' and C:/x (niubash, brush native); Git Bash (BASH=/usr/bin/*): ':' and /c/x; Linux: ':'.
case \${OSTYPE-} in msys* | cygwin* | windows*) _ay_os=w ;; *) if [ -n "\${WINDIR-}" ]; then _ay_os=w; else _ay_os=l; fi ;; esac
_ay_s=: _ay_g=
if [ "$_ay_os" = w ]; then
  _ay_h=\${USERPROFILE-}
  case \${BASH-} in /usr/bin/* | /bin/*) _ay_g=1 ;; *) _ay_s=';' ;; esac
else
  _ay_h=$HOME
fi
# Prepends $1 to PATH when it exists and is absent; with $2 (m), moves it to the front when it is already there.
# Membership by \`case\`: \${PATH//...} costs 40-100 ms per call under niubash 1.5.0 (long PATH); the move (prefix and
# suffix removal) only applies to the "front" entries that are not already first.
_ay_pp() {
  local d=\${1//\\\\//} b x q="$_ay_s$PATH$_ay_s"
  [ -d "$d" ] || return 0
  if [ -n "$_ay_g" ]; then b=\${d:0:1}; d="/\${b,,}\${d:2}"; b=$d; else b=\${d//\\//\\\\}; fi
  case $q in
    *"$_ay_s$d$_ay_s"* | *"$_ay_s$b$_ay_s"*)
      [ -n "\${2-}" ] || return 0
      case $q in "$_ay_s$d$_ay_s"* | "$_ay_s$b$_ay_s"*) return 0 ;; esac
      # Removal by prefix/suffix (%% and #*), fast under niubash, instead of \${q//...}.
      for x in "$d" "$b"; do
        case $q in *"$_ay_s$x$_ay_s"*) q="\${q%%"$_ay_s$x$_ay_s"*}$_ay_s\${q#*"$_ay_s$x$_ay_s"}" ;; esac
      done
      q=\${q#"$_ay_s"}; PATH=\${q%"$_ay_s"} ;;
  esac
  PATH="$d\${PATH:+$_ay_s$PATH}"
}
if [ "$_ay_os" = w ]; then
${branch(win, "windows")}
else
${branch(!win, "linux")}
fi
export PATH
unset _ay_os _ay_s _ay_g _ay_h
unset -f _ay_pp
`;
}

export function emitPs1(e: EnvToml, h: Host): string {
  const val = (ps: Part[]) =>
    ps
      .map((x) => ("lit" in x ? `'${x.lit.replaceAll("'", "''")}'` : "home" in x ? "$_ayH" : `$env:${x.ref}`))
      .join(" + ") || "''";
  const branch = (active: boolean, plat: Plat) => {
    if (!active) return "  $_ayD = @()";
    const l: string[] = [];
    for (const v of vars(e, plat, h))
      l.push(v.keep ? `  if (-not $env:${v.name}) { $env:${v.name} = ${val(v.value)} }` : `  $env:${v.name} = ${val(v.value)}`);
    l.push(`  $_ayD = @(${dirs(e, plat).map((d) => `(${val(parts(d, h))})`).join(", ")})`);
    return l.join("\n");
  };
  const win = h.plat === "windows";
  return `# ${HEADER}
# pwsh 7 and Windows PowerShell 5.1: $env:* only, no cmdlet (no module load), no subprocess, no network; idempotent.
# PATH in one pass: the existing directories of env.toml first, then the inherited PATH without duplicates
# (case-insensitive, trailing \\ ignored).
$_ayW = $env:OS -eq 'Windows_NT'
if ($_ayW) { $_ayH = $env:USERPROFILE } else { $_ayH = $env:HOME }
if ($_ayW) {
${branch(win, "windows")}
} else {
${branch(!win, "linux")}
}
$_ayS = [IO.Path]::PathSeparator
$_ayL = [Collections.Generic.List[string]]::new()
$_ayK = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach ($_ayX in $_ayD) { if ([IO.Directory]::Exists($_ayX) -and $_ayK.Add($_ayX.TrimEnd('\\'))) { $_ayL.Add($_ayX) } }
foreach ($_ayX in $env:PATH.Split($_ayS)) { if ($_ayX -and $_ayK.Add($_ayX.TrimEnd('\\'))) { $_ayL.Add($_ayX) } }
$env:PATH = [string]::Join($_ayS, $_ayL)
$_ayW = $null; $_ayH = $null; $_ayD = $null; $_ayS = $null; $_ayL = $null; $_ayK = $null; $_ayX = $null
`;
}

// --- the plan: files to write, as (path, content) -------------------------------------------------------------------

/** A file the installer owns. `content: null` means the file must not exist. */
export interface Target {
  file: string;
  content: string | null;
  label: string;
}

/** The shell cache directory: AY_SHELL_CACHE of env.toml for this platform. */
export function cacheDir(e: EnvToml, h: Host): string {
  const d = e.var.AY_SHELL_CACHE;
  const v = (h.plat === "windows" ? d?.windows : d?.linux) ?? d?.all ?? join("{home}", ".cache", "shell");
  return normalize(v.replaceAll("{home}", h.home));
}

/** A `dst` of links.toml for a platform, expanded; undefined when the platform has none. */
export function expandDst(dst: string | Partial<Record<Plat, string>>, h: Host): string | undefined {
  const raw = typeof dst === "string" ? dst : (dst[h.plat] ?? (h.plat === "darwin" ? dst.linux : undefined));
  if (!raw) return undefined;
  const config = process.env.XDG_CONFIG_HOME ?? join(h.home, ".config");
  return normalize(
    raw
      .replace(/^~(?=[\\/]|$)/, h.home)
      .replaceAll("{appdata}", h.appdata)
      .replaceAll("{localappdata}", h.localappdata)
      .replaceAll("{config}", config),
  );
}

/** The one-line file that sources `src` from this checkout. */
export const stub = (src: string) => `# managed by aysh tools/shells.ts (config/links.toml)\n. ${sq(slashes(src))}\n`;

export interface Link {
  shell: string;
  src: string;
  dst: string | Partial<Record<Plat, string>>;
  mode: "source" | "copy";
}

export const loadLinks = (h: Host): Link[] =>
  (Bun.TOML.parse(readFileSync(join(CONFIG(h), "links.toml"), "utf8")) as { link?: Link[] }).link ?? [];

/** The bash family needs no binary check: it is what the stubs are for. */
const ALWAYS = new Set(["bash"]);

export function linkTargets(h: Host, links: Link[]): { targets: Target[]; info: string[] } {
  const targets: Target[] = [];
  const info: string[] = [];
  for (const l of links) {
    const dst = expandDst(l.dst, h);
    if (!dst) continue;
    if (!ALWAYS.has(l.shell) && !h.which(l.shell)) {
      info.push(`info ${l.shell} not on PATH: ${l.src} not installed`);
      continue;
    }
    const src = join(CONFIG(h), l.src);
    const content =
      l.mode === "copy" ? readFileSync(src, "utf8").replaceAll("{src_root}", slashes(srcRoot(h))) : stub(src);
    targets.push({ file: dst, content, label: `${l.mode} ${l.src} -> ${dst}` });
  }
  return { targets, info };
}

/** Candidate git completion scripts for the installed git, nearest first. */
export function gitCompletionCandidates(execPath: string | null, h: Host): string[] {
  const shares = [
    ["share", "git", "completion", "git-completion.bash"],
    ["share", "git-core", "contrib", "completion", "git-completion.bash"],
    ["share", "bash-completion", "completions", "git"],
  ];
  const p = h.plat === "windows" ? win32 : posix; // the path flavor of the target host, not of the machine running this
  const out: string[] = [];
  if (execPath) {
    // <prefix>/libexec/git-core (or lib/git-core): share/ sits under the prefix, or one to three levels above it
    // (Git for Windows keeps it in mingw64/ or ucrt64/ next to the install root).
    let d = p.dirname(p.dirname(p.resolve(execPath.trim())));
    for (let i = 0; i < 4; i++) {
      for (const rel of shares) out.push(p.join(d, ...rel));
      d = p.dirname(d);
    }
  }
  if (h.programfiles)
    for (const sub of ["ucrt64", "mingw64", "clangarm64", ""]) out.push(p.join(h.programfiles, "Git", sub, ...shares[0]));
  return [...new Set(out)];
}

/** The bash completions of git and bun, and of `ay` when an `ay` is on PATH, in the cache directory. */
export function completionTargets(e: EnvToml, h: Host, exists: (p: string) => boolean = existsSync): { targets: Target[]; info: string[] } {
  const comp = join(cacheDir(e, h), "comp");
  const targets: Target[] = [];
  const info: string[] = [];
  if (h.which("git")) {
    const found = gitCompletionCandidates(h.run(["git", "--exec-path"]), h).find(exists);
    if (found) targets.push({ file: join(comp, "git.bash"), content: readFileSync(found, "utf8"), label: `git completion <- ${found}` });
    else info.push("info git completion script not found next to the installed git");
  }
  if (h.which("bun") && h.which("carapace")) {
    const bun = h.run(["carapace", "bun", "bash"]);
    if (bun) targets.push({ file: join(comp, "bun.bash"), content: bun, label: "bun completion <- carapace" });
  }
  const ay = join(cacheDir(e, h), "ay-completion.bash");
  targets.push({
    file: ay,
    content: h.which("ay") ? readFileSync(join(CONFIG(h), "bash", "ay-completion.bash"), "utf8") : null,
    label: "ay completion (bash)",
  });
  return { targets, info };
}

// --- `ay` completions for carapace (pwsh): the spec is read from `ay --help` -----------------------------------------

interface Opt {
  short?: string;
  long?: string;
  value: boolean;
  desc: string;
}
interface Cmd {
  name: string;
  desc: string;
  opts: Opt[];
  cmds: Cmd[];
}

/** Subcommands and options of one `--help` page (clap, or argh where valued options show only in the Usage line). */
export function parseHelp(text: string): { cmds: { name: string; desc: string }[]; opts: Opt[] } {
  const cmds: { name: string; desc: string }[] = [];
  const opts: Opt[] = [];
  let sec = "";
  const usage = text.match(/^Usage:.*$/m)?.[0] ?? "";
  const valued = new Set([...usage.matchAll(/(--[\w-]+) </g)].map((x) => x[1]));
  for (const line of text.split(/\r?\n/)) {
    const head = line.match(/^(\w[\w ]*):\s*$/);
    if (head) {
      sec = head[1];
      continue;
    }
    if (sec === "Commands") {
      const m = line.match(/^ {2}([a-z][\w-]*)(?:\s{2,}(.*))?$/);
      if (m && m[1] !== "help") cmds.push({ name: m[1], desc: (m[2] ?? "").trim() });
    } else if (sec === "Options") {
      const m = line.match(/^ {2,6}(?:(-[A-Za-z0-9]),? ?)?(--[\w-]+)?(?:, [\w-]+)?((?:[ =][<[][^\s]*)*)\s*(.*)$/);
      if (m && (m[1] || m[2]))
        opts.push({ short: m[1], long: m[2], value: !!m[3].trim() || (!!m[2] && valued.has(m[2])), desc: m[4].trim() });
    }
  }
  return { cmds, opts };
}

function crawl(h: Host, ay: string, path: string[], desc: string, depth: number): Cmd | null {
  const text = h.run([ay, ...path, "--help"]);
  if (!text || !/Usage:/.test(text)) return null;
  const p = parseHelp(text);
  const leaf = (c: { name: string; desc: string }): Cmd => ({ name: c.name, desc: c.desc, opts: [], cmds: [] });
  const cmds = p.cmds.map((c) => (depth < 3 ? (crawl(h, ay, [...path, c.name], c.desc, depth + 1) ?? leaf(c)) : leaf(c)));
  return { name: path.at(-1) ?? "ay", desc: desc || text.split(/\r?\n/)[0].trim(), opts: p.opts, cmds };
}

export function carapaceSpec(c: Cmd): unknown {
  const flags: Record<string, string> = {};
  for (const o of c.opts) flags[[o.short, o.long].filter(Boolean).join(", ") + (o.value ? "=" : "")] = o.desc;
  return {
    name: c.name,
    description: c.desc,
    ...(c.opts.length ? { flags } : {}),
    ...(c.cmds.length ? { commands: c.cmds.map(carapaceSpec) } : {}),
  };
}

/** The carapace spec of `ay`, when an `ay` and carapace are installed. */
export function aySpecTarget(h: Host): { targets: Target[]; info: string[] } {
  const ay = h.which("ay");
  if (!ay || !h.which("carapace")) return { targets: [], info: ["info ay or carapace absent: no ay spec for carapace"] };
  const root = crawl(h, ay, [], "", 0);
  if (!root) return { targets: [], info: ["info ay --help unreadable: no ay spec for carapace"] };
  const file = join(h.plat === "windows" ? h.appdata : (process.env.XDG_CONFIG_HOME ?? join(h.home, ".config")), "carapace", "specs", "ay.yaml");
  return { targets: [{ file, content: `${JSON.stringify(carapaceSpec(root), null, 2)}\n`, label: "carapace spec ay" }], info: [] };
}

// --- applying --------------------------------------------------------------------------------------------------------

const read = (f: string) => (existsSync(f) ? readFileSync(f, "utf8") : null);

/** Compares or writes one target; returns the output line. */
export function put(t: Target, check: boolean): string {
  const have = read(t.file);
  if (t.content === null) {
    if (have === null) return `ok   ${t.label} absent`;
    if (!check) rmSync(t.file);
    return `${check ? "DIFF" : "rm  "} ${t.label}: ${t.file} removed`;
  }
  if (have === t.content) return `ok   ${t.label}`;
  if (!check) {
    mkdirSync(dirname(t.file), { recursive: true });
    writeFileSync(t.file, t.content);
  }
  return `${check ? "DIFF" : "set "} ${t.label}`;
}

/**
 * The init caches the bash rc generates (bash-*.bash) are derived from it: the ones older than the rc are stale and
 * removed, so that the next launch regenerates them with the current filters.
 */
export function staleCaches(cache: string, bashrc: string, check: boolean): string[] {
  if (!existsSync(cache) || !existsSync(bashrc)) return [];
  const newest = statSync(bashrc).mtimeMs;
  const res: string[] = [];
  for (const name of readdirSync(cache)) {
    const f = join(cache, name);
    if (!/^bash-.+\.bash$/.test(name) || statSync(f).mtimeMs >= newest) continue;
    if (!check) rmSync(f);
    res.push(`${check ? "DIFF" : "rm  "} stale cache ${name}`);
  }
  return res;
}

/** ~/.gitconfig includes the delta configuration when delta is installed. */
export function gitInclude(h: Host, delta: string, check: boolean): string {
  const gitconfig = join(h.home, ".gitconfig");
  const raw = read(gitconfig) ?? "";
  const label = "gitconfig include delta.gitconfig";
  if (raw.toLowerCase().includes("delta.gitconfig")) return `ok   ${label}`;
  if (!check) writeFileSync(gitconfig, `${raw}${raw && !raw.endsWith("\n") ? "\n" : ""}\n[include]\n\tpath = ${slashes(delta)}\n`);
  return `${check ? "DIFF" : "set "} ${label}`;
}

const winExpand = (s: string, h: Host) => s.replace(/%USERPROFILE%/gi, h.home).replace(/%LOCALAPPDATA%/gi, h.localappdata);

/** [persist.windows]: variables read before a process starts must exist in HKCU\Environment. */
function persist(e: EnvToml, h: Host, check: boolean): string[] {
  const res: string[] = [];
  const q = Bun.spawnSync(["reg", "query", "HKCU\\Environment"], { stdout: "pipe", stderr: "pipe" }).stdout.toString();
  const have = new Map<string, string>();
  for (const line of q.split(/\r?\n/)) {
    const m = line.match(/^\s+(\S+)\s+REG_(?:EXPAND_)?SZ\s*(.*)$/);
    if (m) have.set(m[1].toLowerCase(), m[2].trim());
  }
  for (const [k, raw] of Object.entries(e.persist?.windows ?? {})) {
    const v = raw.replaceAll("{home}", h.home);
    const cur = have.get(k.toLowerCase());
    // keep: an existing HKCU value pointing to an existing directory is the machine's choice and is never overwritten.
    if (e.var[k]?.keep && cur && existsSync(winExpand(cur, h))) {
      res.push(`ok   HKCU\\Environment ${k} kept (${cur})`);
      continue;
    }
    const ok = cur !== undefined && winExpand(cur, h) === v;
    res.push(`${ok ? "ok  " : check ? "DIFF" : "set "} HKCU\\Environment ${k}=${v}${ok ? "" : ` (current: ${cur ?? "absent"})`}`);
    if (!ok && !check) Bun.spawnSync(["setx", k, v], { stdout: "pipe", stderr: "pipe" });
  }
  return res;
}

/** Runs the whole installation; returns the output lines. */
export function install(h: Host, opts: { check: boolean; genOnly?: boolean }): string[] {
  const e = loadEnv(h);
  const cache = cacheDir(e, h);
  const res: string[] = [];
  const apply = (r: { targets: Target[]; info: string[] }) => {
    res.push(...r.info);
    for (const t of r.targets) res.push(put(t, opts.check));
  };

  apply({
    targets: [
      { file: join(cache, "env.sh"), content: emitSh(e, h), label: "env.sh" },
      { file: join(cache, "env.ps1"), content: emitPs1(e, h), label: "env.ps1" },
    ],
    info: [],
  });
  apply(completionTargets(e, h));
  apply(aySpecTarget(h));
  if (opts.genOnly) return res;

  const links = loadLinks(h);
  apply(linkTargets(h, links));
  res.push(...staleCaches(cache, join(CONFIG(h), "bash", "bashrc"), opts.check));
  const delta = links.find((l) => l.shell === "delta");
  const deltaDst = delta && expandDst(delta.dst, h);
  if (deltaDst && h.which("delta")) res.push(gitInclude(h, deltaDst, opts.check));
  if (h.plat === "windows") res.push(...persist(e, h, opts.check));
  return res;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const res = install(currentHost(), { check, genOnly: process.argv.includes("--gen") });
  console.log(res.join("\n"));
  process.exit(check && res.some((r) => r.startsWith("DIFF")) ? 1 : 0);
}
