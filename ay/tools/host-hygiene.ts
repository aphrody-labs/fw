#!/usr/bin/env bun
// Declarative disk hygiene for the fleet hosts: one policy, enforced by size and idleness, replacing ad hoc purges.
//   bun tools/host-hygiene.ts                         dry run on every host of ay.local.toml [hosts] (prints what would go)
//   bun tools/host-hygiene.ts --apply                 apply it now
//   bun tools/host-hygiene.ts --apply --disable-undeclared   also disable custom systemd units not in [hygiene.systemd] keep
//   bun tools/host-hygiene.ts install                 install the script and an ay-hygiene.timer on each host (replaces fleet-clean.timer)
//   bun tools/host-hygiene.ts <host-alias> ...        only these hosts
// Policy numbers are in ay.toml [hygiene]; host paths and unit names (protect, roots, systemd keep) are in ay.local.toml
// [hygiene]. What it covers: cargo target dirs (size cap for all of a host's targets together, oldest evicted first, plus idle
// age), node_modules idle for N days (bun reinstalls them from its hard-linked cache), sccache caches, rustup toolchains other
// than the one pinned by rust-toolchain.toml, docker and podman images/builders/containers, nginx logs (and `nginx -t`), the
// systemd journal and failed units, and custom units nobody declared.
import { readAy, repoRoot } from "./local.ts";
import { readFileSync } from "node:fs";
import { join } from "node:path";

type Json = Record<string, any>;

export interface Policy {
  targetCapGb: number;
  targetIdleDays: number;
  nodeModulesIdleDays: number;
  sccacheCapGb: number;
  dockerKeepHours: number;
  journalMax: string;
  logMaxMb: number;
  keepToolchains: string[];
  roots: string[];
  protect: string[];
  systemdKeep: string[];
}

const SAFE = /^[\w.\/*@:+-]+$/;
const positive = (v: unknown, name: string, fallback: number): number => {
  const n = v === undefined ? fallback : Number(v);
  if (!Number.isFinite(n) || n <= 0) throw new Error(`hygiene: ${name} must be a positive number`);
  return n;
};
const safeList = (v: unknown, name: string): string[] => {
  const list = (v ?? []) as unknown[];
  if (!Array.isArray(list)) throw new Error(`hygiene: ${name} must be a list`);
  return list.map(String).map(s => {
    if (!SAFE.test(s)) throw new Error(`hygiene: ${name} entry ${JSON.stringify(s)} has characters outside [A-Za-z0-9_./*@:+-]`);
    return s;
  });
};

/** The pinned Rust channel of the checkout (rust-toolchain.toml), the only toolchain kept on a host. */
export function pinnedChannel(root = repoRoot): string {
  const toml = Bun.TOML.parse(readFileSync(join(root, "rust-toolchain.toml"), "utf8")) as Json;
  return String(toml.toolchain?.channel ?? "stable");
}

export function resolvePolicy(ay: Json = readAy(), channel: string = pinnedChannel()): Policy {
  const h: Json = ay.hygiene ?? {};
  const journalMax = String(h.journal_max ?? "500M");
  if (!/^\d+[KMG]$/.test(journalMax)) throw new Error("hygiene: journal_max must look like 500M");
  return {
    targetCapGb: positive(h.target_cap_gb, "target_cap_gb", 40),
    targetIdleDays: positive(h.target_idle_days, "target_idle_days", 2),
    nodeModulesIdleDays: positive(h.node_modules_idle_days, "node_modules_idle_days", 7),
    sccacheCapGb: positive(h.sccache_cap_gb, "sccache_cap_gb", 20),
    dockerKeepHours: positive(h.docker_keep_hours, "docker_keep_hours", 48),
    journalMax,
    logMaxMb: positive(h.log_max_mb, "log_max_mb", 50),
    keepToolchains: [channel, ...safeList(h.keep_toolchains, "keep_toolchains")],
    roots: safeList(h.roots ?? ["/home", "/root", "/srv"], "roots"),
    protect: safeList(h.protect, "protect"),
    systemdKeep: safeList(h.systemd?.keep, "systemd.keep"),
  };
}

const arr = (xs: string[]) => `(${xs.map(x => `'${x}'`).join(" ")})`;

/** The bash that enforces the policy on one host. `role` is the host role (`prod` never prunes volumes or stopped containers). */
export function renderScript(p: Policy, role: string, apply: boolean, disableUndeclared = false): string {
  return `#!/usr/bin/env bash
# generated by tools/host-hygiene.ts: do not edit on the host
set -u
APPLY=${apply ? 1 : 0}
ROLE='${role}'
DISABLE_UNDECLARED=${disableUndeclared ? 1 : 0}
ROOTS=${arr(p.roots)}
PROTECT=${arr(p.protect)}
KEEP_TOOLCHAINS=${arr(p.keepToolchains)}
UNIT_KEEP=${arr(p.systemdKeep)}
TARGET_CAP_KB=$(( ${p.targetCapGb} * 1048576 ))
SCCACHE_CAP_BYTES=$(( ${p.sccacheCapGb} * 1073741824 ))
act() { if [ "$APPLY" = 1 ]; then "$@"; else echo "would: $*"; fi; }
mb() { du -sm "$1" 2>/dev/null | cut -f1; }
protected() { local q; for q in "\${PROTECT[@]}"; do case "$1" in "$q"|"$q"/*) return 0;; esac; done; return 1; }
free() { df -BM --output=avail / | tail -1 | tr -dc 0-9; }
before=$(free)

# 1. cargo targets: idle > ${p.targetIdleDays} d go; then oldest first until all targets together fit ${p.targetCapGb} GB. Never while cargo or rustc runs.
if pgrep -x cargo >/dev/null || pgrep -x rustc >/dev/null; then
  echo "targets: skipped (cargo or rustc is running)"
else
  mapfile -t T < <(find "\${ROOTS[@]}" -xdev -maxdepth 8 -name CACHEDIR.TAG -path '*/target/CACHEDIR.TAG' -printf '%h\\n' 2>/dev/null)
  total=0; rows=(); keep=()
  for d in "\${T[@]}"; do protected "$d" && continue; rows+=("$(stat -c %Y "$d") $(du -sk "$d" | cut -f1) $d"); done
  now=$(date +%s)
  while read -r ts kb d; do
    [ -n "$d" ] || continue
    if [ $(( (now - ts) / 86400 )) -ge ${p.targetIdleDays} ]; then echo "target idle: $d $((kb / 1024)) MiB"; act rm -rf --one-file-system "$d"; else total=$((total + kb)); keep+=("$ts $kb $d"); fi
  done < <(printf '%s\\n' "\${rows[@]}" | sort -n)
  while read -r ts kb d; do
    [ -n "$d" ] || continue
    if [ "$total" -gt "$TARGET_CAP_KB" ]; then echo "target over cap: $d $((kb / 1024)) MiB"; act rm -rf --one-file-system "$d"; total=$((total - kb)); fi
  done < <(printf '%s\\n' "\${keep[@]:-}" | sort -n)
fi

# 2. node_modules next to a package.json, idle > ${p.nodeModulesIdleDays} d (bun restores them from its cache)
while IFS= read -r d; do
  protected "$d" && continue
  [ -f "$(dirname "$d")/package.json" ] || continue
  echo "node_modules idle: $d $(mb "$d") MiB"; act rm -rf --one-file-system "$d"
done < <(find "\${ROOTS[@]}" -xdev -type d -name node_modules -prune -mtime +${p.nodeModulesIdleDays} -print 2>/dev/null)

# 3. sccache caches over ${p.sccacheCapGb} GB: least recently used first
for d in /var/cache/*/sccache /var/cache/sccache /home/*/.cache/sccache /root/.cache/sccache; do
  [ -d "$d" ] || continue
  size=$(du -sb "$d" | cut -f1)
  if [ "$size" -gt "$SCCACHE_CAP_BYTES" ]; then
    echo "sccache over cap: $d $((size / 1048576)) MiB"
    if [ "$APPLY" = 1 ]; then find "$d" -type f -printf '%A@ %s %p\\n' | sort -n | awk -v cap="$SCCACHE_CAP_BYTES" '{ t += $2; f[NR] = $3; s[NR] = $2 } END { for (i = 1; i <= NR && t > cap; i++) { print f[i]; t -= s[i] } }' | xargs -r rm -f; fi
  fi
done

# 4. rustup toolchains other than the pinned one
for t in /home/*/.rustup/toolchains/* /root/.rustup/toolchains/*; do
  [ -d "$t" ] || continue
  name=$(basename "$t"); keepit=0
  for k in "\${KEEP_TOOLCHAINS[@]}"; do case "$name" in "$k"-*|"$k") keepit=1;; esac; done
  [ "$keepit" = 1 ] || { echo "toolchain not pinned: $t $(mb "$t") MiB"; act rm -rf "$t"; }
done

# 5. containers: images unused for ${p.dockerKeepHours} h, build cache; stopped containers and volumes only off the prod role
for c in docker podman; do
  command -v $c >/dev/null || continue
  act $c image prune -af --filter "until=${p.dockerKeepHours}h" >/dev/null
  [ "$c" = docker ] && act docker builder prune -f --filter "until=${p.dockerKeepHours}h" >/dev/null
  if [ "$ROLE" != prod ]; then act $c container prune -f --filter "until=${p.dockerKeepHours}h" >/dev/null; act $c volume prune -f >/dev/null; fi
done

# 6. nginx: logs over ${p.logMaxMb} MB truncated, rotated logs older than 3 d removed, configuration must still parse
if [ -d /var/log/nginx ]; then
  find /var/log/nginx -type f \\( -name '*.gz' -o -name '*.[0-9]' \\) -mtime +3 -print 2>/dev/null | while read -r f; do act rm -f "$f"; done
  find /var/log/nginx -type f -name '*.log' -size +${p.logMaxMb}M -print 2>/dev/null | while read -r f; do act truncate -s 0 "$f"; done
  command -v nginx >/dev/null && { nginx -t 2>&1 | tail -1; }
fi

# 7. systemd: failed units, journal cap, custom units nobody declared
act systemctl reset-failed
act journalctl -q --vacuum-size=${p.journalMax}
for f in /etc/systemd/system/*.service /etc/systemd/system/*.timer; do
  [ -f "$f" ] && [ ! -L "$f" ] || continue
  u=$(basename "$f"); ok=0
  for k in "\${UNIT_KEEP[@]}"; do case "$u" in $k|$k.service|$k.timer) ok=1;; esac; done
  [ "$ok" = 1 ] && continue
  echo "undeclared unit: $u"
  [ "$DISABLE_UNDECLARED" = 1 ] && act systemctl disable --now "$u"
done

echo "free on /: \${before} MiB -> $(free) MiB"
`;
}

export function renderUnits(): { service: string; timer: string } {
  return {
    service: `[Unit]\nDescription=ay host hygiene (cargo targets, node_modules, caches, toolchains, containers, journal)\n[Service]\nType=oneshot\nNice=19\nIOSchedulingClass=idle\nCPUWeight=10\nExecStart=/usr/local/bin/ay-hygiene\n`,
    timer: `[Unit]\nDescription=ay host hygiene every 30 minutes\n[Timer]\nOnBootSec=5min\nOnUnitActiveSec=30min\nRandomizedDelaySec=120\n[Install]\nWantedBy=timers.target\n`,
  };
}

/** The root script that installs the hygiene script and its timer on a host (fleet-clean.timer is replaced, not kept beside it). */
export function renderInstall(p: Policy, role: string): string {
  const { service, timer } = renderUnits();
  return `set -e
cat > /usr/local/bin/ay-hygiene <<'AY_HYGIENE_SCRIPT'
${renderScript(p, role, true, false)}
AY_HYGIENE_SCRIPT
chmod 755 /usr/local/bin/ay-hygiene
cat > /etc/systemd/system/ay-hygiene.service <<'AY_UNIT'
${service}AY_UNIT
cat > /etc/systemd/system/ay-hygiene.timer <<'AY_UNIT'
${timer}AY_UNIT
systemctl daemon-reload
systemctl disable --now fleet-clean.timer 2>/dev/null || true
systemctl enable --now ay-hygiene.timer
systemctl is-active ay-hygiene.timer
`;
}

function roleOf(ay: Json, alias: string): string {
  return Object.entries((ay.hosts ?? {}) as Json).find(([, a]) => a === alias)?.[0] ?? "build";
}

async function ssh(alias: string, script: string): Promise<{ code: number; out: string }> {
  const p = Bun.spawn(["ssh", "-o", "BatchMode=yes", alias, "sudo -n bash -s"], { stdin: new Blob([script]), stdout: "pipe", stderr: "pipe" });
  const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
  return { code, out: (out + err).trim() };
}

async function main(argv: string[]): Promise<number> {
  const ay = readAy();
  const policy = resolvePolicy(ay);
  const install = argv.includes("install");
  const apply = argv.includes("--apply");
  const disableUndeclared = argv.includes("--disable-undeclared");
  const named = argv.filter(a => !a.startsWith("--") && a !== "install");
  const hosts = named.length ? named : Object.values((ay.hosts ?? {}) as Record<string, string>);
  if (!hosts.length) throw new Error("hygiene: no host (set [hosts] in ay.local.toml)");
  const results = await Promise.all(
    hosts.map(async alias => {
      const role = roleOf(ay, alias);
      if (!install) return { alias, ...(await ssh(alias, renderScript(policy, role, apply, disableUndeclared))) };
      const setup = renderInstall(policy, role);
      return { alias, ...(await ssh(alias, setup)) };
    }),
  );
  for (const r of results) console.log(`== ${r.alias}${r.code ? ` (exit ${r.code})` : ""}\n${r.out}\n`);
  return results.some(r => r.code) ? 1 : 0;
}

if (import.meta.main) process.exit(await main(Bun.argv.slice(2)));
