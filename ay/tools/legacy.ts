#!/usr/bin/env bun
// Inventory the legacy monorepo (ay.toml [legacy]) so the rebuild does not regress: every app, Bun package, Rust
// crate, Go and Python module, third-party pin and external dependency, with the product it belongs to (keywords of
// ay.toml [products]) and its state here: `ported` (a unit of the same name exists in this repository), `tracked`
// (named in the feature matrix or a research dataset) or `review` (nothing here covers it yet).
//   bun tools/legacy.ts [--checkout <path>] (or AY_LEGACY_CHECKOUT; skipped when there is no checkout) [--out <file> (default .private/legacy-inventory.toml)] [--summary]
import { privatePath } from "./local.ts";
import { readAy } from "./local.ts";
import { existsSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");

export type Kind = "app" | "package" | "crate" | "go" | "python" | "third_party" | "dir";
export type State = "ported" | "tracked" | "review";
export type Unit = {
  kind: Kind;
  name: string;
  path: string;
  description: string;
  files: number;
  product: string;
  state: State;
  url?: string;
  fork?: string;
  pillar?: string;
};
export type Dep = { ecosystem: "cargo" | "npm"; name: string; version: string; users: number };

type Toml = Record<string, any>;
const readToml = async (path: string): Promise<Toml | undefined> => {
  const f = Bun.file(path);
  if (!(await f.exists())) return undefined;
  try {
    return Bun.TOML.parse(await f.text()) as Toml;
  } catch {
    return undefined;
  }
};
const readJson = async (path: string): Promise<any> => {
  const f = Bun.file(path);
  return (await f.exists()) ? f.json().catch(() => undefined) : undefined;
};

/** Words of a name or path: `frameworks/m3-tokens` → ["frameworks", "m3", "tokens"]. */
export function words(text: string): string[] {
  return text.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
}

/** The product whose keywords match the most words of the unit's name and path; "platform" when none match. */
export function classify(name: string, path: string, keywords: Record<string, string[]>): string {
  const ws = new Set([...words(name), ...words(path)]);
  let best = "platform";
  let score = 0;
  for (const [product, keys] of Object.entries(keywords)) {
    const s = keys.filter(k => ws.has(k)).length;
    if (s > score) [best, score] = [product, s];
  }
  return best;
}

/** Normalised identity used to match a legacy unit with a unit of this repository. */
export function norm(name: string): string {
  return name.toLowerCase().replace(/^@[^/]+\//, "").replace(/^(ay|aphrody)[_-]/, "").replace(/[_-]/g, "");
}

export function stateOf(name: string, here: Set<string>, corpus: string): State {
  const n = norm(name);
  if (here.has(n)) return "ported";
  if (n.length > 2 && corpus.includes(n)) return "tracked";
  return "review";
}

/** Count tracked files under each prefix with one `git ls-files` pass. */
export function countFiles(files: string[], prefixes: string[]): Map<string, number> {
  const out = new Map(prefixes.map(p => [p, 0]));
  const sorted = [...prefixes].sort((a, b) => b.length - a.length);
  for (const f of files) {
    const p = sorted.find(p => f === p || f.startsWith(p + "/"));
    if (p) out.set(p, out.get(p)! + 1);
  }
  return out;
}

const q = (s: string) => JSON.stringify(s);
export function toToml(units: Unit[], deps: Dep[], meta: Record<string, string>): string {
  const lines = ["# Generated by `bun tools/legacy.ts`; rerun it instead of editing.", ""];
  lines.push("[meta]", ...Object.entries(meta).map(([k, v]) => `${k} = ${q(v)}`), "");
  for (const u of units) {
    lines.push("[[unit]]");
    for (const [k, v] of Object.entries(u)) if (v !== undefined && v !== "") lines.push(`${k} = ${typeof v === "number" ? v : q(String(v))}`);
    lines.push("");
  }
  for (const d of deps) lines.push("[[dep]]", `ecosystem = ${q(d.ecosystem)}`, `name = ${q(d.name)}`, `version = ${q(d.version)}`, `users = ${d.users}`, "");
  return lines.join("\n");
}

const depVersion = (v: any): string => (typeof v === "string" ? v : v?.version ?? (v?.git ? `git:${v.git}` : v?.path ? `path:${v.path}` : v?.workspace ? "workspace" : ""));

async function scan(checkout: string) {
  const ay = readAy(root) as Toml;
  const keywords: Record<string, string[]> = Object.fromEntries(Object.entries(ay.products ?? {}).map(([k, v]: any) => [k, v.keywords ?? [k]]));
  const units: Unit[] = [];
  const cargoUse = new Map<string, Dep>();
  const npmUse = new Map<string, Dep>();
  const use = (m: Map<string, Dep>, ecosystem: Dep["ecosystem"], name: string, v: any) => {
    const version = depVersion(v);
    if (version.startsWith("path:") || version === "workspace" || String(version).startsWith("workspace:")) return;
    const d = m.get(name) ?? { ecosystem, name, version, users: 0 };
    d.users++;
    if (!d.version && version) d.version = version;
    m.set(name, d);
  };

  // Rust crates: the root workspace members.
  const cargo = await readToml(join(checkout, "Cargo.toml"));
  for (const [n, v] of Object.entries(cargo?.workspace?.dependencies ?? {})) use(cargoUse, "cargo", n, v);
  for (const m of cargo?.workspace?.members ?? []) {
    const c = await readToml(join(checkout, m, "Cargo.toml"));
    if (!c?.package) continue;
    units.push({ kind: "crate", name: c.package.name, path: m, description: c.package.description ?? "", files: 0, product: "", state: "review" });
    for (const sect of ["dependencies", "dev-dependencies", "build-dependencies"]) for (const [n, v] of Object.entries(c[sect] ?? {})) use(cargoUse, "cargo", n, v);
  }

  // Bun packages: the root workspaces, globs expanded.
  const pkg = await readJson(join(checkout, "package.json"));
  const patterns: string[] = Array.isArray(pkg?.workspaces) ? pkg.workspaces : pkg?.workspaces?.packages ?? [];
  const pkgDirs = new Set<string>();
  for (const p of patterns) {
    if (!p.includes("*")) pkgDirs.add(p);
    else for await (const f of new Bun.Glob(`${p}/package.json`).scan({ cwd: checkout, onlyFiles: true })) pkgDirs.add(f.replace(/\\/g, "/").replace(/\/package\.json$/, ""));
  }
  for (const [n, v] of Object.entries(pkg?.catalog ?? {})) use(npmUse, "npm", n, v);
  for (const d of pkgDirs) {
    const p = await readJson(join(checkout, d, "package.json"));
    if (!p) continue;
    units.push({ kind: "package", name: p.name ?? d, path: d, description: p.description ?? "", files: 0, product: "", state: "review" });
    for (const sect of ["dependencies", "devDependencies", "peerDependencies"]) for (const [n, v] of Object.entries(p[sect] ?? {})) use(npmUse, "npm", n, v);
  }

  // Apps: every folder of apps/ not already listed as a package.
  for await (const d of new Bun.Glob("apps/*").scan({ cwd: checkout, onlyFiles: false })) {
    const path = d.replace(/\\/g, "/");
    if (pkgDirs.has(path) || (await Bun.file(join(checkout, path)).exists())) continue;
    const p = await readJson(join(checkout, path, "package.json"));
    const c = await readToml(join(checkout, path, "Cargo.toml"));
    units.push({ kind: "app", name: p?.name ?? c?.package?.name ?? path.slice(5), path, description: p?.description ?? c?.package?.description ?? "", files: 0, product: "", state: "review" });
  }

  // Go modules and Python projects.
  const gowork = await Bun.file(join(checkout, "go.work")).text().catch(() => "");
  for (const m of gowork.matchAll(/^\s*use\s+(\S+)/gm)) units.push({ kind: "go", name: m[1].replace(/^\.\//, ""), path: m[1].replace(/^\.\//, ""), description: "", files: 0, product: "", state: "review" });
  const py = await readToml(join(checkout, "pyproject.toml"));
  for (const m of py?.tool?.uv?.workspace?.members ?? []) units.push({ kind: "python", name: m, path: m, description: "", files: 0, product: "", state: "review" });

  // Third-party pins.
  const lock = await readJson(join(checkout, "src.lock.json"));
  for (const [path, r] of Object.entries<any>(lock?.repositories ?? {})) {
    units.push({ kind: "third_party", name: path.split("/").pop()!, path, description: "", files: 0, product: "", state: "review", url: r.url, fork: r.remotes?.aphrody, pillar: r.pillar });
  }

  // First-party folders of the layer directories that no manifest covers (code without a manifest still counts).
  const covered = new Set(units.map(u => u.path));
  for (const layer of ["system", "frameworks", "hardware", "device", "kernel", "plugins", "tools", "scripts"]) {
    for await (const d of new Bun.Glob(`${layer}/*`).scan({ cwd: checkout, onlyFiles: false })) {
      const path = d.replace(/\\/g, "/");
      if (covered.has(path) || [...covered].some(c => c.startsWith(path + "/")) || (await Bun.file(join(checkout, path)).exists())) continue;
      units.push({ kind: "dir", name: path.split("/").pop()!, path, description: "", files: 0, product: "", state: "review" });
    }
  }

  // What this repository already has, and what the matrix and research datasets name.
  const here = new Set<string>();
  for (const g of ["crates/*/Cargo.toml", "packages/*/package.json", "apps/*"]) for await (const f of new Bun.Glob(g).scan({ cwd: root, onlyFiles: false })) here.add(norm(f.replace(/\\/g, "/").split("/")[1]));
  for (const m of (await Bun.file(join(root, ".gitmodules")).text().catch(() => "")).matchAll(/path = (\S+)/g)) here.add(norm(m[1].split("/").pop()!));
  let corpus = "";
  for (const g of ["docs/*.{toml,md}", "docs/research/*.{toml,md}", "docs/adr/*.md"]) for await (const f of new Bun.Glob(g).scan({ cwd: root })) if (!f.includes("legacy-inventory")) corpus += (await Bun.file(join(root, f)).text()).toLowerCase().replace(/[_-]/g, "");

  const files = (await Bun.$`git -C ${checkout} ls-files`.quiet().text()).split("\n").filter(Boolean);
  const counts = countFiles(files, units.map(u => u.path));
  for (const u of units) {
    u.files = counts.get(u.path) ?? 0;
    u.product = classify(u.name, u.path, keywords);
    u.state = stateOf(u.name, here, corpus);
  }
  const deps = [...cargoUse.values(), ...npmUse.values()].sort((a, b) => b.users - a.users || a.name.localeCompare(b.name));
  const head = (await Bun.$`git -C ${checkout} rev-parse HEAD`.quiet().text()).trim();
  return { units, deps, head, repo: ay.legacy?.repo ?? "" };
}

export function summary(units: Unit[], deps: Dep[]): string {
  const by = (f: (u: Unit) => string) => {
    const m = new Map<string, Record<State, number>>();
    for (const u of units) {
      const r = m.get(f(u)) ?? { ported: 0, tracked: 0, review: 0 };
      r[u.state]++;
      m.set(f(u), r);
    }
    return [...m].sort().map(([k, r]) => `| ${k} | ${r.ported} | ${r.tracked} | ${r.review} |`);
  };
  return [
    "| kind | ported | tracked | review |", "|---|---|---|---|", ...by(u => u.kind), "",
    "| product | ported | tracked | review |", "|---|---|---|---|", ...by(u => u.product), "",
    `external dependencies: ${deps.filter(d => d.ecosystem === "cargo").length} cargo, ${deps.filter(d => d.ecosystem === "npm").length} npm`,
  ].join("\n");
}

if (import.meta.main) {
  const arg = (k: string) => {
    const i = process.argv.indexOf(k);
    return i > 0 ? process.argv[i + 1] : undefined;
  };
  const ay = readAy(root) as Toml;
  const hint = arg("--checkout") ?? process.env.AY_LEGACY_CHECKOUT ?? ay.legacy?.checkout;
  const checkout = hint ? resolve(root, hint) : "";
  if (!checkout || !existsSync(join(checkout, ".git"))) {
    console.log("no legacy checkout (--checkout, AY_LEGACY_CHECKOUT or ay.toml [legacy].checkout): inventory skipped, the committed one is unchanged");
    process.exit(0);
  }
  const out = resolve(root, arg("--out") ?? privatePath("legacy-inventory.toml", root, true));
  const { units, deps, head, repo } = await scan(checkout);
  await Bun.write(out, toToml(units, deps, { repo, commit: head, scanned: new Date().toISOString().slice(0, 10) }));
  console.log(`${units.length} units, ${deps.length} external dependencies → ${out}`);
  if (process.argv.includes("--summary")) console.log(summary(units, deps));
}
