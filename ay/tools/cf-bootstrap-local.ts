#!/usr/bin/env bun
// Generates git-ignored `cf.local.toml` from live Cloudflare API + ~/.ssh/config.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { createCloudflareClient } from "../packages/cf-control-plane/src/index.ts";
import { readAy } from "./local.ts";

const root = resolve(import.meta.dir, "..");
const outPath = join(root, "cf.local.toml");

function parseSshHosts(): Record<string, string> {
  const cfgPath = join(homedir(), ".ssh", "config");
  const ips: Record<string, string> = {};
  if (!existsSync(cfgPath)) return ips;
  let currentAliases: string[] = [];
  for (const raw of readFileSync(cfgPath, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (/^Host\s+/i.test(line)) {
      currentAliases = line.replace(/^Host\s+/i, "").split(/\s+/);
    } else if (/^HostName\s+/i.test(line)) {
      const host = line.replace(/^HostName\s+/i, "").trim();
      for (const alias of currentAliases) {
        if (!/^10\./.test(host)) ips[alias] = host;
      }
    }
  }
  return ips;
}

const client = createCloudflareClient();
const accountsPage = await client.accounts.list({ per_page: 20 });
const account = (accountsPage.result ?? [])[0];
if (!account) throw new Error("No Cloudflare account visible for active CLOUDFLARE_API_TOKEN");

const accountId = account.id;
const [zonesPage, tunnelsPage] = await Promise.all([
  client.zones.list({ per_page: 50 }),
  client.zeroTrust.tunnels.cloudflared.list({ account_id: accountId, is_deleted: false }),
]);

const ssh = parseSshHosts();
// Host aliases by role come from ay.toml / ay.local.toml [hosts]; nothing is named here.
const roles = (readAy(root).hosts ?? {}) as Record<string, string>;
const alias = (role: string) => roles[role] ?? "";
const buildWork = ((readAy(root).paths ?? {}) as Record<string, { work?: string }>).build?.work ?? "";
const zoneItems = zonesPage.result ?? [];
const zones = zoneItems.map((z) => `"${z.name}" = "${z.id}"`);
const tunnels = (tunnelsPage.result ?? []).map((t) => `${String(t.name)} = "${String(t.id)}"`);

let buildIpv6 = "";
let edgeProxyIpv6 = "";
const aphrodyComZone = zoneItems.find((z) => z.name === "aphrody.com");
if (aphrodyComZone) {
  const dnsPage = await client.dns.records.list({ zone_id: aphrodyComZone.id, per_page: 100 });
  for (const rec of dnsPage.result ?? []) {
    if (rec.type === "AAAA" && rec.name === "vps.aphrody.com") buildIpv6 = String(rec.content ?? "");
    if (rec.type === "AAAA" && rec.name === "dbfr.aphrody.com") edgeProxyIpv6 = String(rec.content ?? "");
  }
}

const toml = [
  "# Auto-generated by `bun tools/cf-bootstrap-local.ts`. GIT-IGNORED: never commit.",
  "",
  "[cloudflare]",
  `account_id = "${accountId}"`,
  "",
  "[cloudflare.zones]",
  ...zones,
  "",
  "[cloudflare.tunnels]",
  ...tunnels,
  "",
  "[hosts.build]",
  `ssh_alias = "${alias("build")}"`,
  `public_ipv4 = "${ssh[alias("build")] ?? ""}"`,
  `public_ipv6 = "${buildIpv6}"`,
  `work_dir = "${buildWork}"`,
  "",
  "[hosts.edge_proxy]",
  `ssh_alias = "${alias("test")}"`,
  `public_ipv4 = "${ssh[alias("test")] ?? ""}"`,
  `public_ipv6 = "${edgeProxyIpv6}"`,
  "",
  "[hosts.origin]",
  `ssh_alias = "${alias("prod")}"`,
  `public_ipv4 = "${ssh[alias("prod")] ?? ""}"`,
  "",
].join("\n");

writeFileSync(outPath, toml, { mode: 0o600 });
console.log(`Wrote git-ignored cf.local.toml (${zones.length} zones, ${tunnels.length} tunnels)`);
