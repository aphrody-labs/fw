#!/usr/bin/env bun
// Builds os/linux/PKGBUILD from Arch's own `linux` PKGBUILD, which is fetched at a pinned commit, so the packaging follows Arch
// and only the documented differences are ours: a mainline rc source (signed git tag), LLVM toolchain, and the Aphrody config fragments
// merged over Arch's base config with Rust required. The pins live in os/linux/linux.toml [kernel]; nothing else is typed here.
//   bun tools/linux-aphrody.ts            fetch the pinned sources, write os/linux/PKGBUILD and its config pins
//   bun tools/linux-aphrody.ts --check    fail when the committed PKGBUILD is not what the pins generate
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");

export type Pins = {
  /** Commit of archlinux/packaging/packages/linux whose PKGBUILD and config.x86_64 are the base. */
  arch_commit: string;
  /** Kernel git tag to build (a mainline release or release candidate). */
  tag: string;
  /** Repository, commit and file names of the config fragments, and the sha256 of every fetched file. */
  fragments_repo: string;
  fragments_commit: string;
  fragments_dir: string;
  fragments: string[];
  sha256: Record<string, string>;
};

export const ARCH_RAW = (commit: string, file: string) => `https://gitlab.archlinux.org/archlinux/packaging/packages/linux/-/raw/${commit}/${file}`;
export const FRAGMENT_RAW = (p: Pins, f: string) => `https://raw.githubusercontent.com/${p.fragments_repo}/${p.fragments_commit}/${p.fragments_dir}/${f}`;

const block = (text: string, name: string): string[] => {
  const m = new RegExp(`^${name}=\\(\\n([\\s\\S]*?)\\n\\)`, "m").exec(text);
  if (!m) throw new Error(`upstream PKGBUILD has no ${name}=( ... ) block: the transformation must be revisited`);
  return m[1]!.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
};

const must = (text: string, anchor: string): void => {
  if (!text.includes(anchor)) throw new Error(`upstream PKGBUILD changed: anchor not found: ${anchor.trim().slice(0, 60)}`);
};

/** The Aphrody PKGBUILD: Arch's file with a new header, a fragment-merging prepare() and an LLVM build. Throws when Arch's shape changed. */
export function transform(arch: string, p: Pins): string {
  const start = arch.indexOf("pkgbase=linux\n");
  const mark = arch.indexOf("export KBUILD_BUILD_HOST");
  if (start < 0 || mark < 0) throw new Error("upstream PKGBUILD changed: header anchors not found");
  const maint = arch.slice(0, start).trimEnd();
  const makedepends = [...new Set([...block(arch, "makedepends"), "clang", "llvm", "lld"])];
  const version = p.tag.replace(/^v/, "").replace(/-rc/, "rc");
  const frag = p.fragments.map((f) => `  ${f}::${FRAGMENT_RAW(p, f)}`);
  const sums = ["SKIP", p.sha256["config.x86_64"]!, ...p.fragments.map((f) => p.sha256[f]!)];
  const header = `# Generated by tools/linux-aphrody.ts from archlinux/packaging/packages/linux at ${p.arch_commit}; do not edit.
${maint.replace(/^# Maintainer:.*$/m, "# Upstream packaging: Arch Linux linux package (heftig and the Arch kernel team)")}

pkgbase=linux-aphrody
pkgver=${version}
pkgrel=1
pkgdesc='Linux (mainline ${p.tag}), Rust enabled, Aphrody configuration fragments'
url='https://www.kernel.org'
arch=(x86_64)
license=(GPL-2.0-only)
makedepends=(
${makedepends.map((d) => `  ${d}`).join("\n")}
)
options=(
  !debug
  !strip
)
_srcname=linux
_srctag=${p.tag}
source=(
  "$_srcname::git+https://git.kernel.org/pub/scm/linux/kernel/git/torvalds/linux.git#tag=$_srctag?signed"
${frag.join("\n")}
)
source_x86_64=(config.x86_64::${ARCH_RAW(p.arch_commit, "config.x86_64")})
validpgpkeys=(
  ABAF11C65A2970B130ABE3C479BE3E4300411886  # Linus Torvalds
  647F28654894E3BD457199BE38DBBDC86092693E  # Greg Kroah-Hartman
)
sha256sums=(${sums.slice(0, 1).concat(sums.slice(2)).map((s) => `'${s}'`).join("\n            ")})
sha256sums_x86_64=('${sums[1]}')

`;
  let body = arch.slice(mark);
  const from = body.indexOf("  local src\n");
  const to = body.indexOf("  make -s kernelrelease > version");
  if (from < 0 || to < 0 || to < from) throw new Error("upstream PKGBUILD changed: prepare() anchors not found");
  const prepare = `  echo "Setting config..."
  cp ../config.$CARCH .config
  make LLVM=1 olddefconfig
  ARCH=x86 scripts/kconfig/merge_config.sh -m .config ${p.fragments.map((f) => `../${f}`).join(" ")}
  make LLVM=1 olddefconfig
  grep -q '^CONFIG_RUST=y' .config || { echo "CONFIG_RUST is not enabled: Android's binder needs it"; return 1; }
  diff -u ../config.$CARCH .config || :

`;
  body = body.slice(0, from) + prepare + body.slice(to);
  must(body, "  make all\n");
  body = body.replace("  make all\n", "  make LLVM=1 all\n");
  must(body, "make -C tools/bpf/bpftool vmlinux.h");
  return header + body;
}

export async function pins(): Promise<Pins> {
  return (Bun.TOML.parse(await Bun.file(join(root, "os/linux/linux.toml")).text()) as { kernel: Pins }).kernel;
}

const sha256 = (bytes: Uint8Array | string) => new Bun.CryptoHasher("sha256").update(bytes).digest("hex");

async function fetchText(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

if (import.meta.main) {
  const p = await pins();
  const arch = await fetchText(ARCH_RAW(p.arch_commit, "PKGBUILD"));
  const sums: Record<string, string> = { "config.x86_64": sha256(await fetchText(ARCH_RAW(p.arch_commit, "config.x86_64"))) };
  for (const f of p.fragments) sums[f] = sha256(await fetchText(FRAGMENT_RAW(p, f)));
  const text = transform(arch, { ...p, sha256: sums });
  const path = join(root, "os/linux/PKGBUILD");
  if (process.argv.includes("--check")) {
    if (!(await Bun.file(path).exists()) || (await Bun.file(path).text()) !== text) (console.error("os/linux/PKGBUILD is stale: run bun tools/linux-aphrody.ts"), process.exit(1));
  } else await Bun.write(path, text);
  console.log(`PKGBUILD from Arch ${p.arch_commit.slice(0, 12)}, tag ${p.tag}, ${p.fragments.length} fragments`);
}
