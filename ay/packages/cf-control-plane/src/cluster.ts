import type { AyCfManifest } from "./schemas.ts";

export interface GeneratedClusterConfigs {
  pingoraYaml: string;
  nginxEdgeProxyConf: string;
  nftablesOriginConf: string;
  mullvadUidScript: string;
  cloudflaredHaYaml: string;
}

export function generateClusterConfigs(
  manifest: AyCfManifest,
  tunnelIds: Record<string, string> = {},
): GeneratedClusterConfigs {
  const originMeshIp = manifest.cluster.origin.mesh_ip;
  const proxyMeshIp = manifest.cluster.edge_proxy.mesh_ip;
  const meshCidr = manifest.cluster.mesh_cidr;
  const quicPort = manifest.cluster.cloudflared_quic_port;

  const pingoraYaml = [
    "# Generated by ay-cf cluster-proxy: OVH edge-proxy Pingora L4/L7 configuration",
    "version: 1",
    "daemon: false",
    "threads: 4",
    "grace_period_seconds: 15",
    `upstream_keepalive_pool_size: 128`,
    "listeners:",
    "  - name: https-origin-shield",
    "    bind: 0.0.0.0:443",
    "    proxy_protocol: false",
    "  - name: mesh-internal",
    `    bind: ${proxyMeshIp}:8080`,
    "upstreams:",
    "  origin_hostinger:",
    `    peer: ${originMeshIp}:443`,
    "    tls: true",
    "    alpn: h2",
    "  garage_cold_s3:",
    `    peer: ${proxyMeshIp}:3900`,
    "    tls: false",
    "sites:",
    ...manifest.site.map(
      (s) => `  - id: ${s.id}\n    zone: ${s.zone}\n    tunnel: ${s.tunnel}\n    backend: ${s.origin_role}`,
    ),
    "",
  ].join("\n");

  const nginxEdgeProxyConf = [
    "# Generated by ay-cf cluster-proxy: OVH edge_proxy Nginx front for non-CF / shield paths",
    `upstream hostinger_origin_mesh { server ${originMeshIp}:8443 max_fails=3 fail_timeout=10s; keepalive 64; }`,
    `upstream garage_s3_local { server 127.0.0.1:3900 keepalive 32; }`,
    "",
    "server {",
    "    listen 8443 ssl http2;",
    "    server_name dragonballfr.com *.dragonballfr.com rosegriffon.fr *.rosegriffon.fr;",
    "    # Accept real client IP only from Cloudflare or internal WireGuard mesh",
    `    set_real_ip_from ${meshCidr};`,
    "    real_ip_header CF-Connecting-IP;",
    "",
    "    location / {",
    "        proxy_pass https://hostinger_origin_mesh;",
    "        proxy_http_version 1.1;",
    "        proxy_set_header Connection \"\";",
    "        proxy_set_header Host $host;",
    "        proxy_set_header X-Forwarded-Proto $scheme;",
    "        proxy_set_header X-Real-IP $remote_addr;",
    "    }",
    "}",
    "",
  ].join("\n");

  const nftablesOriginConf = [
    "#!/usr/sbin/nft -f",
    "# Generated by ay-cf cluster-proxy: Hostinger origin firewall (zero exposed public app ports)",
    "flush ruleset",
    "",
    "table inet ay_cf_origin {",
    "    chain input {",
    "        type filter hook input priority 0; policy drop;",
    "        iifname \"lo\" accept",
    "        ct state established,related accept",
    "        ct state invalid drop",
    "        ip protocol icmp accept",
    "        ip6 nexthdr ipv6-icmp accept",
    "",
    "        # WireGuard mesh + Mullvad return traffic",
    `        ip saddr ${meshCidr} accept`,
    "        udp dport 51820 accept",
    "",
    "        # SSH operator administration (restrict further via bastion / SSH keys only)",
    "        tcp dport 22 ct state new limit rate 15/minute accept",
    "    }",
    "",
    "    chain output {",
    "        type filter hook output priority 0; policy accept;",
    `        # Allow outbound cloudflared QUIC (${quicPort}/udp + tcp fallback) and WireGuard`,
    "    }",
    "}",
    "",
  ].join("\n");

  const exitBlocks = manifest.vpn.exit.map(
    (e) =>
      [
        `# Exit '${e.id}' (${e.purpose}: ${e.country}/${e.city}) -> user vpn-${e.id} (uid ${e.uid}), table ${e.table}`,
        `id -u vpn-${e.id} >/dev/null 2>&1 || useradd --system --uid ${e.uid} --no-create-home --shell /usr/sbin/nologin vpn-${e.id}`,
        `# Add inside /etc/wireguard/wg-${e.id}.conf [Interface]:`,
        `# Table = ${e.table}`,
        `# PostUp = ip rule add to ${meshCidr} lookup main priority 50; ip rule add uidrange ${e.uid}-${e.uid} lookup ${e.table} priority 100; ip -6 rule add uidrange ${e.uid}-${e.uid} lookup ${e.table} priority 100`,
        `# PostDown = ip rule del uidrange ${e.uid}-${e.uid} lookup ${e.table} priority 100; ip -6 rule del uidrange ${e.uid}-${e.uid} lookup ${e.table} priority 100; ip rule del to ${meshCidr} lookup main priority 50`,
      ].join("\n"),
  );

  const mullvadUidScript = [
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "# Generated by ay-cf cluster-proxy: Mullvad WireGuard UID split-tunnel installer",
    "# Never overrides table main, SSH, WireGuard mesh, or cloudflared QUIC tunnels.",
    "",
    ...exitBlocks,
    "",
  ].join("\n");

  const tunnelSections = Object.entries(manifest.tunnels).map(([name, cfg]) => {
    const id = tunnelIds[name] ?? `<${name}-tunnel-uuid>`;
    const ingress = cfg.ingress.map((host) => `    - hostname: ${host}\n      service: https://127.0.0.1:443`).join("\n");
    return [
      `# Tunnel: ${name} (protocol=${cfg.transport}, connectors=${cfg.connectors})`,
      `tunnel: ${id}`,
      `protocol: ${cfg.transport}`,
      "metrics: 127.0.0.1:20241",
      "ingress:",
      ingress,
      "    - service: http_status:404",
    ].join("\n");
  });

  return {
    pingoraYaml,
    nginxEdgeProxyConf,
    nftablesOriginConf,
    mullvadUidScript,
    cloudflaredHaYaml: tunnelSections.join("\n\n---\n\n") + "\n",
  };
}
