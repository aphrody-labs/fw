// material.aphrody.com: the Material CDN.
//
// Static tree: R2 bucket MATERIAL, key `v1/...` (tools/material-cdn builds and publishes it): per-icon SVGs, sprites, full and unicode-range
// fonts, the Rust tables, M3 tokens, the Aphrody icons, versioned assets under `assets/<name>/<version>/`.
// À la carte: icons.svg, icons.json, icon.svg, icons.woff2, icons.css and fonts/<slug>.woff2|css build exactly the icons, characters and
// axes a request names (HarfBuzz hb-subset and a Rust WOFF2 encoder, both wasm), see tools/material-cdn/grammar.ts for the parameters.
//
// Cache policy
//   immutable (public, max-age=31536000, immutable):
//     - content-addressed files: `<name>.<sha256 first 8 hex>.woff2|ttf`, `g/<hash>.<ext>` generated objects
//     - versioned crate tarballs `rust/<major>.<minor>.<patch>.tar.gz[.sha256]` and everything under `assets/<name>/<version>/`
//     - any file requested with `?v=<sha256 first 8..64 hex>` when the object's SHA-256 matches; a stale pin is a 404, never wrong bytes
//     - generated output requested with `?v=<rev>` (the meta.json revision): the revision is part of the hash
//   generated output without `v` is cached for a day (ETag revalidation); everything else mutable (index.json, CSS, sprites, stable paths): short TTL with stale-while-revalidate.
// Generated results are stored in R2 (`v1/gen/<hash>.<ext>`) and the Cache API, keyed by sha256(algorithm, revision, output, canonical query).
import { GrammarError, EXTENSION, identity, canonicalQuery, type Need, type Output, outputOf, parse } from "../../tools/material-cdn/grammar.ts";
import { fontCss, iconFont, iconsCss, textFont } from "./src/fonts.ts";
import { etagMatches, GENERATED, IMMUTABLE, MIME, MUTABLE, problem, reply, sha256Hex } from "./src/http.ts";
import { pathList, single, sprite } from "./src/icons.ts";
import { loadMeta, type Meta } from "./src/meta.ts";
import { SubsetError } from "./src/hb.ts";

/** Bump when the generated bytes of a request change for the same inputs (code change in the builders). */
const ALGORITHM = "1";

const HASHED_FILE = /\.[0-9a-f]{8}\.(woff2|ttf)$/;
const VERSIONED_CRATE = /^v1\/rust\/\d+\.\d+\.\d+\.tar\.gz(\.sha256)?$/;
const VERSIONED_ASSET = /^v1\/assets\/[a-z0-9_-]+\/[A-Za-z0-9._+-]*\d[A-Za-z0-9._+-]*\/.+/;
const GENERATED_KEY = /^g\/([0-9a-f]{20})\.(svg|json|woff2|css)$/;
const VALID_KEY = /^v1\/[A-Za-z0-9_\-./]+$/;
const MAX_BODY = 256 * 1024;

const notFound = (cache = "public, max-age=60") => reply(404, "not found\n", { "Cache-Control": cache, "Content-Type": "text/plain; charset=utf-8" });

async function origin(request: Request, env: Env, key: string, pin: string | null): Promise<Response> {
  const ext = key.slice(key.lastIndexOf(".") + 1);
  const type = MIME[ext] ?? "application/octet-stream";
  const immutableName = HASHED_FILE.test(key) || VERSIONED_CRATE.test(key) || VERSIONED_ASSET.test(key);
  const headers: Record<string, string> = { "Content-Type": type, "Accept-Ranges": "bytes" };
  if (ext === "svg") headers["Content-Security-Policy"] = "default-src 'none'; style-src 'unsafe-inline'; sandbox";

  if (pin) {
    // Validate the pin against the bytes: cheap for SVGs, once per edge location (the result is cached) for fonts.
    const obj = await env.MATERIAL.get(key);
    if (!obj) return notFound();
    const buf = await obj.arrayBuffer();
    const sum = await sha256Hex(buf);
    if (!sum.startsWith(pin)) return reply(404, "pinned hash does not match the current object\n", { "Cache-Control": "no-store", "Content-Type": "text/plain; charset=utf-8" });
    return reply(200, buf, { ...headers, "Cache-Control": IMMUTABLE, ETag: `"${sum}"` });
  }

  const obj = await env.MATERIAL.get(key, { onlyIf: request.headers, range: request.headers });
  if (!obj) return notFound();
  headers["Cache-Control"] = immutableName ? IMMUTABLE : MUTABLE;
  headers.ETag = obj.httpEtag;
  headers["Last-Modified"] = obj.uploaded.toUTCString();
  if (!("body" in obj) || obj.body === undefined) return reply(304, null, headers);
  const body = obj as R2ObjectBody;
  let status = 200;
  if (body.range && "offset" in body.range && request.headers.has("Range")) {
    const r = body.range as { offset: number; length: number };
    headers["Content-Range"] = `bytes ${r.offset}-${r.offset + r.length - 1}/${body.size}`;
    headers["Content-Length"] = String(r.length);
    status = 206;
  } else {
    headers["Content-Length"] = String(body.size);
  }
  return reply(status, body.body, headers);
}

// ------------------------------------------------------------------ generated outputs

async function build(env: Env, meta: Meta, need: Need): Promise<string | Uint8Array> {
  switch (need.output) {
    case "sprite":
      return sprite(env, meta, need);
    case "json":
      return pathList(env, meta, need);
    case "icon":
      return single(env, meta, need);
    case "icons-font":
      return iconFont(env, meta, need);
    case "icons-css":
      return iconsCss(env, meta, need);
    case "font":
      return textFont(env, meta, need);
    case "font-css":
      return fontCss(meta, need);
  }
}

async function readBody(request: Request): Promise<URLSearchParams> {
  const extra = new URLSearchParams();
  const text = await request.text();
  if (text.length > MAX_BODY) throw new GrammarError(`body larger than ${MAX_BODY} bytes`);
  if (!text.trim()) return extra;
  const type = request.headers.get("Content-Type") ?? "";
  if (type.includes("json")) {
    const body = JSON.parse(text) as Record<string, unknown>;
    if (typeof body !== "object" || body === null || Array.isArray(body)) throw new GrammarError("the JSON body must be an object of parameters");
    for (const [k, v] of Object.entries(body)) {
      if (v === undefined || v === null) continue;
      const numbers = Array.isArray(v) && v.every((n) => typeof n === "number") ? (v as number[]) : undefined;
      extra.set(k, numbers && k === "fill" ? `${Math.min(...numbers)}..${Math.max(...numbers)}` : Array.isArray(v) ? v.join(",") : String(v));
    }
  } else extra.set("icons", text.replace(/\s+/g, ","));
  return extra;
}

async function generated(request: Request, env: Env, ctx: ExecutionContext, url: URL, routed: { output: Output; family?: string }): Promise<Response> {
  const started = performance.now();
  // fonts/material-symbols-<style>.woff2|css is the icon font of that style.
  const symbolsStyle = /^material-symbols-(outlined|rounded|sharp)$/.exec(routed.family ?? "")?.[1];
  const route = symbolsStyle ? { output: routed.output === "font" ? ("icons-font" as const) : ("icons-css" as const), family: undefined } : routed;
  if (symbolsStyle && !url.searchParams.has("style")) url.searchParams.set("style", symbolsStyle);
  let need: Need;
  let meta: Meta;
  try {
    meta = await loadMeta(env);
    const params = new URLSearchParams(url.search);
    if (request.method === "POST") for (const [k, v] of await readBody(request)) if (!params.has(k)) params.set(k, v);
    need = parse(route.output, params, route.family).need;
  } catch (e) {
    return failure(e);
  }
  const rev = need.v ?? meta.rev;
  const ext = EXTENSION[route.output];
  const hash = (await sha256Hex(`${ALGORITHM}|${rev}|${route.output}|${route.family ?? ""}|${canonicalQuery(identity(need))}`)).slice(0, 20);
  const pinned = need.v !== undefined;
  const id = `g/${hash}.${ext}`;
  const cacheKey = new Request(`https://${url.host}/v1/${id}`, { method: "GET" });
  const cache = (caches as unknown as { default: Cache }).default;
  const headers = (source: string): Record<string, string> => ({
    "Content-Type": MIME[ext]!,
    "Cache-Control": pinned ? IMMUTABLE : GENERATED,
    ETag: `"${hash}"`,
    "Content-Location": `/v1/${id}`,
    "X-Material-Source": source,
    "Server-Timing": `gen;dur=${(performance.now() - started).toFixed(1)};desc="${source}"`,
  });
  const finish = (source: string, body: BodyInit | null, extra: Record<string, string> = {}) => {
    const h = { ...headers(source), ...extra };
    if (etagMatches(request.headers.get("If-None-Match"), h.ETag!)) return reply(304, null, { ETag: h.ETag!, "Cache-Control": h["Cache-Control"]!, "X-Material-Source": source });
    return reply(200, request.method === "HEAD" ? null : body, h);
  };

  const cached = request.method !== "POST" ? await cache.match(cacheKey) : undefined;
  if (cached) return finish("edge-cache", cached.body);

  const stored = await env.MATERIAL.get(`v1/gen/${hash}.${ext}`);
  if (stored) {
    const bytes = await stored.arrayBuffer();
    ctx.waitUntil(cache.put(cacheKey, reply(200, bytes, { "Content-Type": MIME[ext]!, "Cache-Control": IMMUTABLE, "Content-Length": String(bytes.byteLength) })));
    return finish("r2", bytes, { "Content-Length": String(bytes.byteLength) });
  }
  if (pinned && need.v !== meta.rev) return problem(404, "this revision is no longer built", { requested: need.v, current: meta.rev });

  let output: string | Uint8Array;
  try {
    output = await build(env, meta, need);
  } catch (e) {
    return failure(e);
  }
  const bytes = typeof output === "string" ? new TextEncoder().encode(output) : output;
  const writes = [
    env.MATERIAL.put(`v1/gen/${hash}.${ext}`, bytes, { httpMetadata: { contentType: MIME[ext]!, cacheControl: IMMUTABLE }, customMetadata: { rev, output: route.output, query: canonicalQuery(identity(need)).slice(0, 1800) } }),
    cache.put(cacheKey, reply(200, bytes, { "Content-Type": MIME[ext]!, "Cache-Control": IMMUTABLE, "Content-Length": String(bytes.byteLength) })),
  ];
  ctx.waitUntil(Promise.all(writes));
  return finish("built", bytes, { "Content-Length": String(bytes.byteLength) });
}

function failure(e: unknown): Response {
  if (e instanceof GrammarError) return problem(400, e.message, e.detail);
  if (e instanceof SyntaxError) return problem(400, "the body is not valid JSON");
  if (e instanceof SubsetError) return problem(422, e.message);
  console.error(JSON.stringify({ message: "generation failed", error: String(e), stack: e instanceof Error ? e.stack : undefined }));
  return problem(500, "generation failed");
}

async function fromStore(request: Request, env: Env, key: string, ext: string): Promise<Response> {
  const object = await env.MATERIAL.get(`v1/gen/${key}`);
  if (!object) return notFound();
  const etag = `"${key.slice(0, 20)}"`;
  const headers = { "Content-Type": MIME[ext]!, "Cache-Control": IMMUTABLE, ETag: etag, "Content-Length": String(object.size) };
  if (etagMatches(request.headers.get("If-None-Match"), etag)) return reply(304, null, { ETag: etag, "Cache-Control": IMMUTABLE });
  return reply(200, request.method === "HEAD" ? null : (object as R2ObjectBody).body, headers);
}

