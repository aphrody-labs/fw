export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    if (request.method === "OPTIONS") return reply(204, null, { "Access-Control-Max-Age": "86400" });
    const post = request.method === "POST";
    if (request.method !== "GET" && request.method !== "HEAD" && !post) return reply(405, "method not allowed\n", { Allow: "GET, HEAD, POST, OPTIONS" });

    if (url.pathname === "/" || url.pathname === "/v1" || url.pathname === "/v1/") {
      if (post) return reply(405, "method not allowed\n", { Allow: "GET, HEAD, OPTIONS" });
      return reply(200, request.method === "HEAD" ? null : JSON.stringify(ROOT, null, 2) + "\n", { "Content-Type": "application/json; charset=utf-8", "Cache-Control": MUTABLE });
    }
    if (url.pathname === "/robots.txt") return reply(200, "User-agent: *\nAllow: /\n", { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": MUTABLE });

    let key: string;
    try {
      key = decodeURIComponent(url.pathname).replace(/^\//, "");
    } catch {
      return notFound();
    }
    if (!VALID_KEY.test(key) || key.includes("..") || key.endsWith("/")) return notFound();
    const relative = key.slice("v1/".length);

    const stored = GENERATED_KEY.exec(relative);
    if (stored && !post) return fromStore(request, env, relative.slice(2), stored[2]!);

    const route = outputOf(relative);
    // The full fonts keep their static css (`fonts/<slug>.css` without parameters); parameters opt into a build.
    const hasNeeds = [...url.searchParams.keys()].some((k) => k !== "v") || post;
    if (route && (post || hasNeeds || route.output !== "font-css")) {
      if (post && !/^icons\.(svg|json|woff2|css)$/.test(relative)) return reply(405, "method not allowed\n", { Allow: "GET, HEAD, OPTIONS" });
      return generated(request, env, ctx, url, route);
    }
    if (post) return reply(405, "method not allowed\n", { Allow: "GET, HEAD, OPTIONS" });

    const v = url.searchParams.get("v");
    const pin = v && /^[0-9a-f]{8,64}$/.test(v) ? v : null;

    // Edge cache keyed by URL (the ?v pin is part of it); HEAD is answered from the GET entry.
    const cacheKey = new Request(url.toString(), { method: "GET" });
    const cache = (caches as unknown as { default: Cache }).default;
    let res = await cache.match(request.method === "GET" ? request : cacheKey);
    if (!res) {
      res = await origin(request.method === "GET" ? request : cacheKey, env, key, pin);
      if (res.status === 200) ctx.waitUntil(cache.put(cacheKey, res.clone()));
    }
    if (request.method === "HEAD") return new Response(null, { status: res.status, headers: res.headers });
    return res;
  },
} satisfies ExportedHandler<Env>;

